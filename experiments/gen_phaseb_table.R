#!/usr/bin/env Rscript
# gen_phaseb_table.R
# Generates LaTeX table: mean RE(%) + median runtime per group x neighbourhood
# for Phase B (irace-tuned TS, all 5 neighbourhoods, 82 instances x 30 runs)

suppressPackageStartupMessages({
  library(dplyr)
  library(tidyr)
})

COR_DIR  <- "C:/Users/diazhernan/CLionProjects/IJSP/Papers/COR_Tabu"
DATA     <- file.path(COR_DIR, "data/phaseB_ts/runs_data.csv")
GROUP_B  <- file.path(COR_DIR, "data/phaseB_ts/phaseB_group_summary.csv")

# ── Lower bounds ──────────────────────────────────────────────────────────────
CLASSICAL_LB <- c(
  abz7=656, abz8=645, abz9=661, ft10=930, ft20=1165,
  la21=1046, la24=935, la25=977, la27=1235, la29=1152, la38=1196, la40=1222
)
TAILLARD_LBS <- list(
  tai15_15=c(1231,1244,1218,1175,1224,1238,1227,1217,1274,1241),
  tai20_15=c(1357,1367,1342,1345,1339,1360,1462,1377,1332,1348),
  tai20_20=c(1642,1561,1518,1644,1558,1591,1652,1603,1583,1528),
  tai30_15=c(1764,1774,1788,1828,2007,1819,1771,1673,1795,1651),
  tai30_20=c(1906,1884,1809,1948,1997,1957,1807,1912,1931,1833),
  tai50_15=c(2760,2756,2717,2839,2679,2781,2943,2885,2655,2723),
  tai50_20=c(2868,2869,2755,2702,2725,2845,2825,2784,3071,2995)
)
get_lb <- function(inst) {
  if (grepl("^F0\\.15\\.0\\.", inst)) {
    name <- sub("^F0\\.15\\.0\\.([a-z]+[0-9]+)_.*", "\\1", inst)
    return(unname(CLASSICAL_LB[name]))
  } else if (grepl("^tai", inst)) {
    group <- sub("^(tai[0-9]+_[0-9]+)_.*", "\\1", inst)
    idx   <- as.integer(sub("^tai[0-9]+_[0-9]+_(\\d+).*", "\\1", inst))
    return(TAILLARD_LBS[[group]][idx])
  }
  NA_real_
}
get_group <- function(inst) {
  if (grepl("^F0\\.15\\.0\\.", inst))
    sub("^F0\\.15\\.0\\.([a-z]+[0-9]+)_.*", "\\1", inst)
  else if (grepl("^tai", inst))
    sub("^(tai[0-9]+_[0-9]+)_.*", "\\1", inst)
  else "unknown"
}

neigh_map <- c(n1="N1", n2="N2", n3="N3", n8="N8", "next"="N_ext", next.="N_ext")
NEIGH_ORDER  <- c("N2","N8","N_ext","N1","N3")
GROUP_ORDER  <- c("abz7","abz8","abz9","ft10","ft20",
                  "la21","la24","la25","la27","la29","la38","la40",
                  "tai15_15","tai20_15","tai20_20",
                  "tai30_15","tai30_20","tai50_15","tai50_20")

# ── Compute mean RE(%) per group x neighbourhood ──────────────────────────────
d <- read.csv(DATA, stringsAsFactors=FALSE)
d$lb     <- sapply(d$instance, get_lb)
d$group  <- sapply(d$instance, get_group)
d$re_pct <- (d$midpoint - d$lb) / d$lb * 100
d$neigh_f <- factor(neigh_map[d$neigh], levels=NEIGH_ORDER)

re_gn <- d %>%
  group_by(group, neigh_f) %>%
  summarise(re_mean=mean(re_pct, na.rm=TRUE), .groups="drop")

# ── Get median runtime per group x neighbourhood ──────────────────────────────
rt <- read.csv(GROUP_B, stringsAsFactors=FALSE) %>%
  mutate(neigh_f = factor(neigh_map[neigh], levels=NEIGH_ORDER)) %>%
  filter(!is.na(neigh_f)) %>%
  select(group, neigh_f, med_rt)

# ── Join and pivot ────────────────────────────────────────────────────────────
joined <- inner_join(re_gn, rt, by=c("group","neigh_f"))

re_wide <- pivot_wider(re_gn,  names_from=neigh_f, values_from=re_mean,
                       names_prefix="re_")
rt_wide <- pivot_wider(rt,      names_from=neigh_f, values_from=med_rt,
                       names_prefix="rt_")
tab <- inner_join(re_wide, rt_wide, by="group")
tab <- tab[match(GROUP_ORDER, tab$group), ]

# ── Grand mean row ────────────────────────────────────────────────────────────
grand_re <- d %>% group_by(neigh_f) %>%
  summarise(re_mean=mean(re_pct,na.rm=TRUE),.groups="drop")
grand_rt <- rt %>% group_by(neigh_f) %>%
  summarise(med_rt=mean(med_rt,na.rm=TRUE),.groups="drop")

# ── Helper: find row-min RE columns ──────────────────────────────────────────
re_cols <- paste0("re_", NEIGH_ORDER)
rt_cols <- paste0("rt_", NEIGH_ORDER)

# Row-min RE per group
tab$min_re_col <- apply(tab[, re_cols], 1, function(x) {
  re_cols[which.min(x)]
})

# ── LaTeX labels for groups ───────────────────────────────────────────────────
group_label <- c(
  abz7="ABZ7", abz8="ABZ8", abz9="ABZ9",
  ft10="FT10", ft20="FT20",
  la21="LA21", la24="LA24", la25="LA25",
  la27="LA27", la29="LA29", la38="LA38", la40="LA40",
  tai15_15="$15{\\times}15$", tai20_15="$20{\\times}15$",
  tai20_20="$20{\\times}20$", tai30_15="$30{\\times}15$",
  tai30_20="$30{\\times}20$", tai50_15="$50{\\times}15$",
  tai50_20="$50{\\times}20$"
)

fmt_re <- function(x) sprintf("%.2f", x)
fmt_rt <- function(x) as.character(round(x))

# ── Build LaTeX ───────────────────────────────────────────────────────────────
header <- c(
"% ============================================================",
"% Table: Phase B mean RE(%) and median runtime by group × neighbourhood",
"% Generated by gen_phaseb_table.R",
"% ============================================================",
"\\begin{table*}[htbp]",
"\\centering\\small\\setlength{\\tabcolsep}{4pt}",
"\\caption{Phase~B: mean RE\\,(\\%) and median runtime $t$\\,(s) per instance group and",
"neighbourhood (irace-tuned TS, 30 runs per instance). Bold: minimum RE\\,(\\%) in each row.",
"Groups are ordered as in Tables~\\ref{tab:lit_classical}--\\ref{tab:lit_taillard_ii}.}",
"\\label{tab:phaseb_groups}",
"\\begin{tabular}{l rr rr rr rr rr}",
"\\hline",
" & \\multicolumn{2}{c}{$N_2$} & \\multicolumn{2}{c}{$N_8$} &",
"  \\multicolumn{2}{c}{$N_{\\rm ext}$} & \\multicolumn{2}{c}{$N_1$} &",
"  \\multicolumn{2}{c}{$N_3$} \\\\",
"Group & RE & $t$ & RE & $t$ & RE & $t$ & RE & $t$ & RE & $t$ \\\\",
"\\hline"
)

rows <- character(0)

# Separator between classical and Taillard
CLASSICAL <- c("abz7","abz8","abz9","ft10","ft20","la21","la24","la25","la27","la29","la38","la40")
TAILLARD  <- c("tai15_15","tai20_15","tai20_20","tai30_15","tai30_20","tai50_15","tai50_20")

for (i in seq_len(nrow(tab))) {
  g <- tab$group[i]
  if (g == "tai15_15") rows <- c(rows, "\\hline")  # separator classical/Taillard

  cells <- character(10)
  for (j in seq_along(NEIGH_ORDER)) {
    n <- NEIGH_ORDER[j]
    re_val <- tab[[paste0("re_",n)]][i]
    rt_val <- tab[[paste0("rt_",n)]][i]
    re_str <- fmt_re(re_val)
    if (tab$min_re_col[i] == paste0("re_",n))
      re_str <- paste0("\\textbf{", re_str, "}")
    cells[(j-1)*2+1] <- re_str
    cells[(j-1)*2+2] <- fmt_rt(rt_val)
  }
  rows <- c(rows, sprintf("%-20s & %s \\\\",
                          group_label[g],
                          paste(cells, collapse=" & ")))
}

# Grand mean row
grand_cells <- character(10)
for (j in seq_along(NEIGH_ORDER)) {
  n <- NEIGH_ORDER[j]
  re_val <- grand_re$re_mean[grand_re$neigh_f==n]
  rt_val <- grand_rt$med_rt[grand_rt$neigh_f==n]
  grand_cells[(j-1)*2+1] <- fmt_re(re_val)
  grand_cells[(j-1)*2+2] <- fmt_rt(rt_val)
}

footer <- c(
"\\hline",
sprintf("\\textit{Grand mean}   & %s \\\\", paste(grand_cells, collapse=" & ")),
"\\hline",
"\\end{tabular}",
"\\end{table*}"
)

tex <- c(header, rows, footer)
tex_str <- paste(tex, collapse="\n")
cat(tex_str, "\n")

# Also write to file
out_path <- file.path(COR_DIR, "figures", "tab_phaseb_groups.tex")
writeLines(tex, out_path)
cat(sprintf("\n[OK] Written to %s\n", out_path))
