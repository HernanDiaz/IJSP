#!/bin/bash
#
# make_arm_setups.sh — write each arm's comparison setup from the elite
# configuration its own tuning produced.
#
# Usage: make_arm_setups.sh [output-directory]
#
# The two arms of the comparison must not share a configuration: an algorithm
# run with parameters tuned for a different algorithm is not that algorithm.
# Each arm therefore gets the configuration irace ranked first for it, taken
# from its own log rather than copied by hand, so that the setup that runs and
# the tuning that produced it cannot drift apart.
#
# What is substituted comes from the tuning; what is overridden here is fixed
# by the comparison and is the same for both arms: ten runs from seed 1, the
# 300 s budget the templates already carry, and the two diversity statistics,
# so that the collapse is measured in the comparison itself and not only in
# the diagnostic runs.
#
set -u

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
EXPERIMENT_DIR="$(cd "${HERE}/.." && pwd)"
TUNING="${EXPERIMENT_DIR}/tuning"
OUT_DIR="${1:-${EXPERIMENT_DIR}/setup}"

# The first line of irace's own summary of what it chose. Taking the parameters
# from the log means the setup cannot claim a configuration the tuning did not
# produce; if the log has no such line the tuning did not finish and there is
# nothing to build a setup from.
best_commandline() {
    awk '/^# Best configurations as commandlines/ { grab = 1; next }
         grab && /^[0-9]+ --/ { id = $1; $1 = ""; sub(/^ /, "");
                                print id "\t" $0; exit }' "$1"
}

build_arm() {
    local arm="$1" out="$2"
    local log="${TUNING}/results_${arm}/irace_${arm}.log"
    local template="${TUNING}/template_${arm}.txt"

    [ -f "${log}" ] || { echo "error: no tuning log at ${log}" >&2; return 1; }
    [ -f "${template}" ] || { echo "error: no template ${template}" >&2; return 1; }

    local line id params
    line=$(best_commandline "${log}")
    if [ -z "${line}" ]; then
        echo "error: ${arm} tuning has not finished (no elite configuration in" \
             "$(basename "${log}")); not writing ${out}" >&2
        return 1
    fi
    id="${line%%$'\t'*}"
    params="${line#*$'\t'}"

    cp "${template}" "${out}"

    # What the comparison fixes rather than the tuning. Done before the
    # placeholders are swept, because the seed is itself a placeholder in the
    # template -- irace varies it -- and the sweep would take the line with it.
    sed -i 's/^seed = .*/seed = 1/' "${out}"
    sed -i 's/^runs = .*/runs = 10/' "${out}"

    # Same substitution rule as the target runner: --key value becomes the
    # IRACE_KEY placeholder, upper-cased.
    # shellcheck disable=SC2086
    set -- ${params}
    while [ $# -gt 0 ]; do
        local key val
        key=$(echo "${1#--}" | tr '[:lower:]' '[:upper:]')
        val="$2"
        sed -i "s|IRACE_${key}\b|${val}|g" "${out}"
        shift 2
    done
    # A placeholder still standing belongs to a conditional parameter this
    # configuration does not use (tournament size without tournament
    # selection, and so on). The solver never reads the line.
    sed -i '/IRACE_/d' "${out}"

    cat >> "${out}" <<'STATS'

# Population diversity, recorded but not tested: hamming is the mean pairwise
# distance between genotypes, normalised; neri is 1 - (avg - best) /
# (worst - best) on the fitness. Together they give the collapse curve.
statistics.3.metric = average
statistics.3.value = hamming
statistics.4.metric = average
statistics.4.value = neri
STATS

    # Header, so the file says where it came from without having to be traced.
    local header
    header=$(mktemp)
    {
        echo "# GENERATED by scripts/make_arm_setups.sh on $(date -u '+%Y-%m-%d %H:%M UTC')."
        echo "# Do not edit: rerun the script. Arm ${arm} of the comparison in"
        echo "# PREREG_ma_vs_abc_v2.md, configuration ${id}, the elite of the tuning"
        echo "# logged in tuning/results_${arm}/irace_${arm}.log:"
        echo "#   ${params}"
        echo "#"
        cat "${out}"
    } > "${header}"
    mv "${header}" "${out}"

    echo "${out}: configuration ${id}"
    echo "   ${params}"
}

mkdir -p "${OUT_DIR}"
status=0
build_arm abc "${OUT_DIR}/prereg2_abc_300s.txt" || status=1
build_arm ma  "${OUT_DIR}/prereg2_ma_300s.txt"  || status=1
exit "${status}"
