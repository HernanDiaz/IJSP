#!/usr/bin/env python3
"""I-030: the current configuration against the original one, at 300 s.

Usage: make_jobs.py wave <N>        with N in 1..3

The protocol asks for the current configuration to be run again at 300 s, the
drift anchor, after every third acceptance. There have been two (I-018 and
I-021), both measured at the short per-class budgets. With the backlog empty
and B-12 closed, this is the most useful thing left: whether the accepted gains
hold outside the budgets they were measured at.

Two cells, run in the same batch and interleaved so that the machine's drift
between days (about 9 %) cannot pose as an effect: `original` is prereg2 and
`current` is setup/ref_I-021.txt. 300 s per run on the 21 open instances; the
per-class budgets are not touched, this is the protocol's own anchor regime.
Five runs per cell and instance on fresh seeds 6001 to 6005, one run per job,
split into three waves of about half an hour: seeds 6001-6002, 6003-6004 and
6005. Nothing is accepted or rejected.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXPERIMENT = os.path.abspath(os.path.join(HERE, "..", ".."))
BASES = {"original": os.path.join(EXPERIMENT, "setup", "prereg2_abc_300s.txt"),
         "current": os.path.join(EXPERIMENT, "setup", "ref_I-021.txt")}
CELLS = ["original", "current"]
FULL = ["ta22", "ta23", "ta25", "ta26", "ta27", "ta29", "ta30", "ta32", "ta33",
        "ta34", "ta40", "ta41", "ta42", "ta43", "ta44", "ta45", "ta46", "ta47",
        "ta48", "ta49", "ta50"]
WAVE_SEEDS = {1: [6001, 6002], 2: [6003, 6004], 3: [6005]}
BUDGET = 300


def setup_text(instance, cell, seed, tag):
    out = []
    for line in open(BASES[cell]).read().splitlines():
        if line.startswith("timelimit = "):
            line = "timelimit = %d" % BUDGET
        elif line.startswith("runs = "):
            line = "runs = 1"
        elif line.startswith("seed = "):
            line = "seed = %d" % seed
        out.append(line)
    header = ("# GENERATED by iter/I-030/make_jobs.py, cell %s, %s, %s (%d s, 1 run, "
              "seed %d). Do not edit.\n" % (cell, instance, tag, BUDGET, seed))
    return header + "\n".join(out) + "\n"


def main():
    if (sys.argv[1:2] or [""])[0] != "wave":
        raise SystemExit(__doc__)
    n = int(sys.argv[2])
    tag = "w%d" % n
    setup_dir = os.path.join(HERE, "setups")
    os.makedirs(setup_dir, exist_ok=True)
    jobs = []
    for seed in WAVE_SEEDS[n]:
        for instance in FULL:
            for cell in CELLS:      # interleaved: the two cells alternate
                name = "%s_%s_%s_s%d" % (instance, cell, tag, seed)
                path = os.path.join(setup_dir, name + ".txt")
                with open(path, "w", newline="\n") as handle:
                    handle.write(setup_text(instance, cell, seed, tag))
                jobs.append("%s\tI-030_%s_s%d_%s\t%s" % (path, tag, seed, cell, instance))
    with open(os.path.join(HERE, "jobs_%s.tsv" % tag), "w", newline="\n") as handle:
        handle.write("# I-030 %s: %d jobs of %d s, cells interleaved\n"
                     % (tag, len(jobs), BUDGET))
        handle.write("\n".join(jobs) + "\n")
    print("%s: %d jobs, %.1f CPU-hours" % (tag, len(jobs), len(jobs) * BUDGET / 3600.0))


if __name__ == "__main__":
    main()
