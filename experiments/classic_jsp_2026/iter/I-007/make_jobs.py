#!/usr/bin/env python3
"""I-007: a concentrated record attempt on ta29, and the run-length question.

Usage: make_jobs.py attempt

I-006 left ta29 two units short: 1627 against a BKS of 1625, from 75 runs of
40 s. The line had already matched 1625 once, in the 300 s regime. So the
whole budget goes on ta29, and it is split three ways by per-run budget at
equal total CPU, because nobody has measured which run length produces the
lowest MINIMUM. The restart analysis chose 40 s for 20x20 on the mean, and a
record does not live in the mean.

    40 s  x 200 runs = 8000 s
   100 s  x  80 runs = 8000 s
   300 s  x  27 runs = 8100 s

Same instance, same configuration, same total CPU, one thing different. There
is no filter and no waves: nothing is being accepted, and the endpoints are
pre-declared in RESEARCH_IDEAS.md. Any run at or below 1625 is a record and
its schedule is the proof.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXPERIMENT = os.path.abspath(os.path.join(HERE, "..", ".."))
BASE = os.path.join(EXPERIMENT, "setup", "prereg2_abc_300s.txt")

INSTANCE = "ta29"
# cell name -> (seconds per run, runs in total, runs per job)
CELLS = {
    "b040": (40, 200, 5),
    "b100": (100, 80, 5),
    "b300": (300, 27, 2),
}


def setup_text(cell, seconds, runs, seed, tag):
    out = []
    for line in open(BASE).read().splitlines():
        if line.startswith("timelimit = "):
            line = "timelimit = %d" % seconds
        elif line.startswith("runs = "):
            line = "runs = %d" % runs
        elif line.startswith("seed = "):
            line = "seed = %d" % seed
        out.append(line)
    header = ("# GENERATED by iter/I-007/make_jobs.py, cell %s, %s, %s\n"
              "# (%d s per run, %d runs, seed %d). Do not edit.\n"
              % (cell, INSTANCE, tag, seconds, runs, seed))
    return header + "\n".join(out) + "\n"


def main():
    if (sys.argv[1:2] or [""])[0] != "attempt":
        raise SystemExit(__doc__)
    setup_dir = os.path.join(HERE, "setups")
    os.makedirs(setup_dir, exist_ok=True)
    jobs = []
    total_cpu = 0
    for cell in sorted(CELLS):
        seconds, total, per_job = CELLS[cell]
        total_cpu += seconds * total
        seed = 1
        chunk = 0
        while seed <= total:
            chunk += 1
            runs = min(per_job, total - seed + 1)
            tag = "%s_c%02d" % (cell, chunk)
            path = os.path.join(setup_dir, "%s_%s.txt" % (INSTANCE, tag))
            with open(path, "w", newline="\n") as handle:
                handle.write(setup_text(cell, seconds, runs, seed, tag))
            jobs.append("%s\tI-007_%s\t%s" % (path, tag, INSTANCE))
            seed += runs
    jobs_path = os.path.join(HERE, "jobs_attempt.tsv")
    with open(jobs_path, "w", newline="\n") as handle:
        handle.write("# I-007 concentrated record attempt on %s: three per-run\n"
                     "# budgets at equal total CPU. %s\n"
                     % (INSTANCE,
                        ", ".join("%s = %d s x %d runs" % (c, CELLS[c][0], CELLS[c][1])
                                  for c in sorted(CELLS))))
        handle.write("\n".join(jobs) + "\n")
    print("attempt: %d jobs -> %s  (%.1f CPU-hours, %d runs on %s)"
          % (len(jobs), os.path.relpath(jobs_path), total_cpu / 3600.0,
             sum(CELLS[c][1] for c in CELLS), INSTANCE))
    for c in sorted(CELLS):
        print("   %s: %3d s x %3d runs = %5.2f CPU-hours"
              % (c, CELLS[c][0], CELLS[c][1], CELLS[c][0] * CELLS[c][1] / 3600.0))


if __name__ == "__main__":
    main()
