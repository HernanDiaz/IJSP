#!/usr/bin/env python3
"""I-006: a record attempt, not an idea to accept or reject.

Usage: make_jobs.py attempt

The objective of this line is to beat or match a best known solution, and a
record lives in the lower tail of the run distribution, not in its mean. Five
iterations measuring mean shifts returned five zeros. This batch buys lottery
tickets instead: many short runs on the instances where our best is closest to
the BKS, in the regime the restart analysis says is right for the lower tail.

There is no filter and no wave structure, because nothing is being accepted.
The batch is one queue, and its endpoints are pre-declared in
RESEARCH_IDEAS.md: any run at or below the BKS is a record and its schedule is
the proof; otherwise the best of N per instance and cell, the mean of the
three lowest, and a sign test on best-of-blocks between the two cells.

Two cells, because the attempt doubles as the extra data the tail question
needs. `control` is the frozen configuration. `freqtie` is the cell I-005
discarded on the mean, whose lower tail went the other way -- 1595 against
1607 on ta30, the best this regime has produced there. Choosing it because of
that is selection on the data, and in a record attempt that is legitimate
precisely because nothing is being inferred: a record is a schedule, not a
p-value. It is declared here so no one has to guess.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXPERIMENT = os.path.abspath(os.path.join(HERE, "..", ".."))
BASE = os.path.join(EXPERIMENT, "setup", "prereg2_abc_300s.txt")

RUNS_TOTAL = 75            # per instance and cell
RUNS_PER_JOB = 5           # so no job runs longer than about 13 minutes
BUDGET = {"20x20": 40, "30x15": 100, "30x20": 150}

SIZE = {}
BKS = {}
for row in open(os.path.join(EXPERIMENT, "taillard_bounds.csv")):
    f = row.strip().split(",")
    if f[0] != "instance":
        SIZE[f[0]] = f[1] + "x" + f[2]

# The shortlist: the instances where our best verified makespan is closest to
# the BKS (JOURNAL 2026-09-21). ta29 was matched once at 1625 in the long
# regime; ta30 is 11 away in this one.
SHORTLIST = ["ta29", "ta30", "ta23", "ta22"]
CELLS = ["control", "freqtie"]


def setup_text(instance, cell, runs, seed, tag):
    out = []
    for line in open(BASE).read().splitlines():
        if line.startswith("timelimit = "):
            line = "timelimit = %d" % BUDGET[SIZE[instance]]
        elif line.startswith("runs = "):
            line = "runs = %d" % runs
        elif line.startswith("seed = "):
            line = "seed = %d" % seed
        out.append(line)
    if cell == "freqtie":
        out.append("")
        out.append("# I-006: the cell I-005 discarded on the mean, kept here because")
        out.append("# its lower tail went the other way. See RESEARCH_IDEAS.md.")
        out.append("localsearch.tails = full")
        out.append("localsearch.tiebreak = frequency")
    header = ("# GENERATED by iter/I-006/make_jobs.py, cell %s, %s, %s\n"
              "# (%s, %d s per run, %d runs, seed %d). Do not edit.\n"
              % (cell, instance, tag, SIZE[instance],
                 BUDGET[SIZE[instance]], runs, seed))
    return header + "\n".join(out) + "\n"


def main():
    if (sys.argv[1:2] or [""])[0] != "attempt":
        raise SystemExit(__doc__)
    setup_dir = os.path.join(HERE, "setups")
    os.makedirs(setup_dir, exist_ok=True)
    chunks = RUNS_TOTAL // RUNS_PER_JOB
    jobs = []
    for chunk in range(1, chunks + 1):
        seed = 1 + RUNS_PER_JOB * (chunk - 1)
        for instance in SHORTLIST:
            for cell in CELLS:
                tag = "c%02d" % chunk
                path = os.path.join(setup_dir, "%s_%s_%s.txt" % (instance, cell, tag))
                with open(path, "w", newline="\n") as handle:
                    handle.write(setup_text(instance, cell, RUNS_PER_JOB, seed, tag))
                jobs.append("%s\tI-006_%s_%s\t%s" % (path, tag, cell, instance))
    jobs_path = os.path.join(HERE, "jobs_attempt.tsv")
    with open(jobs_path, "w", newline="\n") as handle:
        handle.write("# I-006 record attempt: %d instances x %d cells x %d runs, "
                     "in %d chunks of %d, seeds 1..%d\n"
                     % (len(SHORTLIST), len(CELLS), RUNS_TOTAL,
                        chunks, RUNS_PER_JOB, RUNS_TOTAL))
        handle.write("\n".join(jobs) + "\n")
    cpu = sum(BUDGET[SIZE[i]] * RUNS_TOTAL * len(CELLS) for i in SHORTLIST)
    print("attempt: %d jobs -> %s  (%.1f CPU-hours, %d runs in total)"
          % (len(jobs), os.path.relpath(jobs_path), cpu / 3600.0,
             RUNS_TOTAL * len(CELLS) * len(SHORTLIST)))


if __name__ == "__main__":
    main()
