#!/usr/bin/env python3
"""I-017: the second local-search call reaches the child it drew.

Usage: make_jobs.py filter
       make_jobs.py wave <N>        with N in 1..6

Two cells. `control` is the frozen configuration. `chosen` sets
abc.ls.pick = chosen. No numeric parameter.

The bug. Every food source makes a pair of children, and MALS_SOME is called on
that pair. It searches the better child, then draws the rest at random without
replacement and applies the tabu search to individual i, the loop counter,
instead of to the one it drew. With a pair the quota trunc(0.4645 x 2) - 1 = -1
wraps round in an unsigned int, the loop walks both children, and the second
call always lands on child 0. Measured 2026-09-23 on one run each: on ta23
20,085 of 37,791 second calls (53 %) and on ta45 45,333 of 86,944 (52 %) went
to the child already searched, from its local optimum, and in each of those
cases the other child went unsearched. With the fix every second call reaches
the other child.

It is not free, and that is the question. Searching a fresh child takes more
iterations than re-searching a local optimum, which dies quickly: iterations
per call rose from 28.7 to 31.0 on ta23 and from 38.4 to 50.1 on ta45, and
generations fell 10 to 18 %. More children polished, or more generations.

The filter uses seeds 1001 to 1030, outside the waves' 1 to 30, so that its
runs are independent of the waves' on the four filter instances (I-017 showed
they were not). One run per job, one results directory per job.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXPERIMENT = os.path.abspath(os.path.join(HERE, "..", ".."))
BASE = os.path.join(EXPERIMENT, "setup", "prereg2_abc_300s.txt")

FILTER_RUNS = 30
FILTER_FIRST_SEED = 1001      # outside the waves' seeds 1..30
WAVE_RUNS = 5
CHUNK = 1
WAVES = 6

BUDGET = {"20x20": 40, "30x15": 100, "30x20": 150}
SIZE = {}
for row in open(os.path.join(EXPERIMENT, "taillard_bounds.csv")):
    f = row.strip().split(",")
    if f[0] != "instance":
        SIZE[f[0]] = f[1] + "x" + f[2]

FULL = ["ta22", "ta23", "ta25", "ta26", "ta27", "ta29", "ta30", "ta32", "ta33",
        "ta34", "ta40", "ta41", "ta42", "ta43", "ta44", "ta45", "ta46", "ta47",
        "ta48", "ta49", "ta50"]
FILTER = ["ta29", "ta30", "ta23", "ta45"]
CELLS = ["control", "chosen"]


def setup_text(instance, cell, runs, seed, tag):
    out = []
    for line in open(BASE).read().splitlines():
        if line.startswith("timelimit = "):
            line = "timelimit = %d" % BUDGET[SIZE[instance]]
        elif line.startswith("runs = "):
            line = "runs = %d" % runs
        elif line.startswith("seed = "):
            line = "seed = %d" % seed
        out.append(line)
    if cell == "chosen":
        out.append("")
        out.append("# I-017: the second tabu call reaches the child it drew")
        out.append("abc.ls.pick = chosen")
    header = ("# GENERATED by iter/I-017/make_jobs.py, cell %s, %s, %s\n"
              "# (%s, %d s per run, %d runs, seed %d). Do not edit.\n"
              % (cell, instance, tag, SIZE[instance], BUDGET[SIZE[instance]],
                 runs, seed))
    return header + "\n".join(out) + "\n"


def write(instances, total_runs, first_seed, tag):
    setup_dir = os.path.join(HERE, "setups")
    os.makedirs(setup_dir, exist_ok=True)
    jobs = []
    for instance in instances:
        for cell in CELLS:
            done = 0
            piece = 0
            while done < total_runs:
                piece += 1
                runs = min(CHUNK, total_runs - done)
                seed = first_seed + done
                name = "%s_%s_%s_p%02d" % (instance, cell, tag, piece)
                path = os.path.join(setup_dir, name + ".txt")
                with open(path, "w", newline="\n") as handle:
                    handle.write(setup_text(instance, cell, runs, seed, tag))
                # One results directory per chunk: the solver names its output
                # by a one-second timestamp, so two concurrent jobs on the same
                # instance in one directory overwrite each other (I-011).
                jobs.append("%s\tI-017_%s_p%02d_%s\t%s"
                            % (path, tag, piece, cell, instance))
                done += runs
    jobs_path = os.path.join(HERE, "jobs_%s.tsv" % tag)
    with open(jobs_path, "w", newline="\n") as handle:
        handle.write("# I-017 %s: %d instances x %d cells x %d runs, one run per job\n"
                     % (tag, len(instances), len(CELLS), total_runs))
        handle.write("\n".join(jobs) + "\n")
    cpu = sum(BUDGET[SIZE[i]] * total_runs * len(CELLS) for i in instances)
    print("%s: %d jobs -> %s  (%.1f CPU-hours)"
          % (tag, len(jobs), os.path.relpath(jobs_path), cpu / 3600.0))


def main():
    which = sys.argv[1] if len(sys.argv) > 1 else ""
    if which == "filter":
        write(FILTER, FILTER_RUNS, FILTER_FIRST_SEED, "filter")
    elif which == "wave":
        try:
            n = int(sys.argv[2])
        except (IndexError, ValueError):
            raise SystemExit(__doc__)
        if not 1 <= n <= WAVES:
            raise SystemExit("wave must be 1..%d" % WAVES)
        write(FULL, WAVE_RUNS, 1 + WAVE_RUNS * (n - 1), "w%d" % n)
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    main()
