#!/usr/bin/env python3
"""I-002: write the setups and the job list for the filter or for one wave.

Usage: make_jobs.py filter
       make_jobs.py wave <N>        with N in 1..6

Every cell is the tuned ABC setup (setup/prereg2_abc_300s.txt, configuration
136, parameters frozen) with the budget per run set by size class and nothing
else changed except, in the `n8` cell, one line: the neighbourhood of the tabu
search. The `control` cell is byte-identical to I-001's control apart from its
runs and seed, so the two batches remain comparable.

The filter runs 30 runs per cell on the four instances fixed in
RESEARCH_IDEAS.md, in six chunks of five runs (tags fc1..fc6, seeds 1, 6, ...,
26) for the same reason the confirmation is waved: a batch's wall clock is
bounded below by its longest single job, so 30 runs of ta45 in one job is 75
minutes no matter how many cores are idle. Chunked, the filter packs into the
14 slots and takes about 20 minutes. I-002's own filter was run unchunked,
before this was noticed. The confirmation runs as six waves of five runs over the 21
open instances, per "Cadencia" in RESEARCH_IDEAS.md: wave w uses runs = 5 and
seed = 1 + 5(w-1), so the six waves together are exactly the same thirty runs
as one batch with seed = 1, and each wave writes to its own results tag
because queue_jobs.sh counts completed runs per directory.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXPERIMENT = os.path.abspath(os.path.join(HERE, "..", ".."))
BASE = os.path.join(EXPERIMENT, "setup", "prereg2_abc_300s.txt")

FILTER_RUNS = 30
FILTER_CHUNKS = 6                  # 6 x 5 runs, so no single job is too long
WAVE_RUNS = 5
WAVES = 6

BUDGET = {"20x20": 40, "30x15": 100, "30x20": 150}
SIZE = {}
for row in open(os.path.join(EXPERIMENT, "taillard_bounds.csv")):
    f = row.strip().split(",")
    if f[0] != "instance":
        SIZE[f[0]] = f[1] + "x" + f[2]

FULL = ["ta22", "ta23", "ta25", "ta26", "ta27", "ta29", "ta30", "ta32", "ta33",
        "ta34", "ta40", "ta41", "ta42", "ta43", "ta44", "ta45", "ta46", "ta47",
        "ta48", "ta49", "ta50"]
FILTER = ["ta29", "ta30", "ta23", "ta45"]          # fixed in RESEARCH_IDEAS.md
CELLS = ["control", "n8"]
NEIGHBOURHOOD = {"control": "jsp.makespan.n2", "n8": "jsp.makespan.n8"}


def setup_text(instance, cell, runs, seed, tag):
    out = []
    for line in open(BASE).read().splitlines():
        if line.startswith("timelimit = "):
            line = "timelimit = %d" % BUDGET[SIZE[instance]]
        elif line.startswith("runs = "):
            line = "runs = %d" % runs
        elif line.startswith("seed = "):
            line = "seed = %d" % seed
        elif line.startswith("localsearch.neighbourhood = "):
            line = "localsearch.neighbourhood = %s" % NEIGHBOURHOOD[cell]
        out.append(line)
    header = ("# GENERATED by iter/I-002/make_jobs.py, cell %s, %s, %s\n"
              "# (%s, %d s per run, %d runs, seed %d). Do not edit.\n"
              % (cell, instance, tag, SIZE[instance],
                 BUDGET[SIZE[instance]], runs, seed))
    return header + "\n".join(out) + "\n"


def write(which, instances, runs, seed, tag):
    setup_dir = os.path.join(HERE, "setups")
    os.makedirs(setup_dir, exist_ok=True)
    jobs = []
    for instance in instances:
        for cell in CELLS:
            path = os.path.join(setup_dir, "%s_%s_%s.txt" % (instance, cell, tag))
            with open(path, "w", newline="\n") as handle:
                handle.write(setup_text(instance, cell, runs, seed, tag))
            jobs.append("%s\tI-002_%s_%s\t%s" % (path, tag, cell, instance))
    jobs_path = os.path.join(HERE, "jobs_%s.tsv" % tag)
    with open(jobs_path, "w", newline="\n") as handle:
        handle.write("# I-002 %s: %d instances x %d cells, %d runs each, seed %d\n"
                     % (tag, len(instances), len(CELLS), runs, seed))
        handle.write("\n".join(jobs) + "\n")
    cpu = sum(BUDGET[SIZE[i]] * runs * len(CELLS) for i in instances)
    print("%s: %d jobs -> %s  (%.1f CPU-hours, ~%.0f min on 14 cores)"
          % (tag, len(jobs), os.path.relpath(jobs_path),
             cpu / 3600.0, cpu / 60.0 / 14))


def main():
    which = sys.argv[1] if len(sys.argv) > 1 else ""
    if which == "filter":
        runs = FILTER_RUNS // FILTER_CHUNKS
        for chunk in range(1, FILTER_CHUNKS + 1):
            write(which, FILTER, runs, 1 + runs * (chunk - 1), "fc%d" % chunk)
    elif which == "wave":
        try:
            n = int(sys.argv[2])
        except (IndexError, ValueError):
            raise SystemExit(__doc__)
        if not 1 <= n <= WAVES:
            raise SystemExit("wave must be 1..%d" % WAVES)
        write(which, FULL, WAVE_RUNS, 1 + WAVE_RUNS * (n - 1), "w%d" % n)
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    main()
