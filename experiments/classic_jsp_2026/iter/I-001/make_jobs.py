#!/usr/bin/env python3
"""I-001: write the setups and the job list for the filter or the full run.

Usage: make_jobs.py filter|full

Every cell is the tuned ABC setup (setup/prereg2_abc_300s.txt, configuration
136, parameters frozen) with three things changed: the budget per run, set
per size class; runs = 30; and, in the seeded cells, the creation. Nothing
else. The cells are interleaved in the job list so that the queue spreads
them evenly over the wall-clock window.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXPERIMENT = os.path.abspath(os.path.join(HERE, "..", ".."))
BASE = os.path.join(EXPERIMENT, "setup", "prereg2_abc_300s.txt")
SEEDS = os.path.join(EXPERIMENT, "seeds")
RUNS = 30
SEED_COUNT = 25

BUDGET = {"20x20": 40, "30x15": 100, "30x20": 150}
SIZE = {}
for row in open(os.path.join(EXPERIMENT, "taillard_bounds.csv")):
    f = row.strip().split(",")
    if f[0] != "instance":
        SIZE[f[0]] = f[1] + "x" + f[2]

FULL = ["ta22", "ta23", "ta25", "ta26", "ta27", "ta29", "ta30", "ta32", "ta33",
        "ta34", "ta40", "ta41", "ta42", "ta43", "ta44", "ta45", "ta46", "ta47",
        "ta48", "ta49", "ta50"]
FILTER = ["ta29", "ta30", "ta23", "ta45"]          # fixed in RESEARCH_IDEAS.md
CELLS = ["control", "v2rand", "v2top", "v2maxmin", "mix"]


def setup_text(instance, cell):
    text = open(BASE).read()
    out = []
    for line in text.splitlines():
        if line.startswith("timelimit = "):
            line = "timelimit = %d" % BUDGET[SIZE[instance]]
        elif line.startswith("runs = "):
            line = "runs = %d" % RUNS
        elif line.startswith("creation = ") and cell != "control":
            line = "creation = jsp.seeded"
        out.append(line)
    if cell != "control":
        pool = os.path.join(SEEDS, "%s_%s.csv" % (instance, cell))
        if not os.path.isfile(pool):
            raise SystemExit("missing pool %s (run prepare_pools.py first)" % pool)
        out.append("")
        out.append("# I-001, cell %s: %d of the population from the pool, the rest random" % (cell, SEED_COUNT))
        out.append("creation.seed.pool = %s" % pool)
        out.append("creation.seed.count = %d" % SEED_COUNT)
    header = ("# GENERATED by iter/I-001/make_jobs.py for cell %s on %s\n"
              "# (%s, %d s per run, %d runs). Do not edit.\n" %
              (cell, instance, SIZE[instance], BUDGET[SIZE[instance]], RUNS))
    return header + "\n".join(out) + "\n"


def main():
    which = sys.argv[1] if len(sys.argv) > 1 else ""
    if which not in ("filter", "full"):
        raise SystemExit(__doc__)
    instances = FILTER if which == "filter" else FULL
    setup_dir = os.path.join(HERE, "setups")
    os.makedirs(setup_dir, exist_ok=True)
    jobs = []
    for instance in instances:
        for cell in CELLS:
            path = os.path.join(setup_dir, "%s_%s.txt" % (instance, cell))
            with open(path, "w", newline="\n") as handle:
                handle.write(setup_text(instance, cell))
            jobs.append("%s\tI-001_%s_%s\t%s" % (path, which, cell, instance))
    jobs_path = os.path.join(HERE, "jobs_%s.tsv" % which)
    with open(jobs_path, "w", newline="\n") as handle:
        handle.write("# I-001 %s: %d instances x %d cells, %d runs each\n"
                     % (which, len(instances), len(CELLS), RUNS))
        handle.write("\n".join(jobs) + "\n")
    cpu = sum(BUDGET[SIZE[i]] * RUNS * len(CELLS) for i in instances)
    print("%s: %d jobs -> %s  (%.1f CPU-hours, ~%.1f h on 14 cores)"
          % (which, len(jobs), os.path.relpath(jobs_path), cpu / 3600.0, cpu / 3600.0 / 14))


if __name__ == "__main__":
    main()
