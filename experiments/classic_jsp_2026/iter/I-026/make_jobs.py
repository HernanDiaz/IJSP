#!/usr/bin/env python3
"""I-026: the extreme tail at 300 s against 40 s, with the current configuration.

Usage: make_jobs.py hunt

I-026 hunted ta29 and ta30 with 400 runs of 40 s per instance, 16,000 s of CPU
each, and reached the best known in 0.25 % and 0.5 % of runs without going
below it. I-025 found, on older data and another configuration, that restarts
win on the median while the outright minimum sometimes comes from a 300 s run,
and ta29's first match in this line came at 300 s (I-007). This batch spends
the same CPU per instance as I-026 on 53 runs of 300 s, so the two regimes can
be set side by side in matches and records per CPU-hour, and it is one more
chance at a record.

One cell, setup/ref_I-021.txt. One run per job so no job exceeds 300 s; fresh
seeds 5001 to 5053. Nothing is accepted or rejected.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXPERIMENT = os.path.abspath(os.path.join(HERE, "..", ".."))
BASE = os.path.join(EXPERIMENT, "setup", "ref_I-021.txt")

INSTANCES = ["ta29", "ta30"]
RUNS_TOTAL = 53           # 53 x 300 s ~ I-024's 400 x 40 s = 16,000 s
RUNS_PER_JOB = 1
FIRST_SEED = 5001
BUDGET = 300


def setup_text(instance, runs, seed, tag):
    out = []
    for line in open(BASE).read().splitlines():
        if line.startswith("timelimit = "):
            line = "timelimit = %d" % BUDGET
        elif line.startswith("runs = "):
            line = "runs = %d" % runs
        elif line.startswith("seed = "):
            line = "seed = %d" % seed
        out.append(line)
    header = ("# GENERATED by iter/I-026/make_jobs.py, %s, %s (%d s per run, %d "
              "runs, seed %d). Do not edit.\n" % (instance, tag, BUDGET, runs, seed))
    return header + "\n".join(out) + "\n"


def main():
    if (sys.argv[1:2] or [""])[0] != "hunt":
        raise SystemExit(__doc__)
    setup_dir = os.path.join(HERE, "setups")
    os.makedirs(setup_dir, exist_ok=True)
    jobs = []
    for chunk in range(1, RUNS_TOTAL // RUNS_PER_JOB + 1):
        seed = FIRST_SEED + RUNS_PER_JOB * (chunk - 1)
        tag = "c%03d" % chunk
        for instance in INSTANCES:
            path = os.path.join(setup_dir, "%s_%s.txt" % (instance, tag))
            with open(path, "w", newline="\n") as handle:
                handle.write(setup_text(instance, RUNS_PER_JOB, seed, tag))
            # one results directory per chunk; the two instances in it write
            # files named by instance, so they cannot collide
            jobs.append("%s\tI-026_%s\t%s" % (path, tag, instance))
    with open(os.path.join(HERE, "jobs_hunt.tsv"), "w", newline="\n") as handle:
        handle.write("# I-026 hunt: %s, %d runs each of %d s, seeds %d..%d\n"
                     % (" ".join(INSTANCES), RUNS_TOTAL, BUDGET, FIRST_SEED,
                        FIRST_SEED + RUNS_TOTAL - 1))
        handle.write("\n".join(jobs) + "\n")
    print("hunt: %d jobs, %d runs, %.1f CPU-hours"
          % (len(jobs), len(jobs) * RUNS_PER_JOB,
             len(jobs) * RUNS_PER_JOB * BUDGET / 3600.0))


if __name__ == "__main__":
    main()
