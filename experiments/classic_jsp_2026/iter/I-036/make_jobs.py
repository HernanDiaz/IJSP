#!/usr/bin/env python3
"""I-036: path relinking as the ABC's crossover.

Usage: make_jobs.py filter
       make_jobs.py wave <N>        with N in 1..6

Two cells. `control` is the current configuration, setup/ref_I-021.txt, with
the JOX crossover. `pr` replaces `crossover = jsp.jox` by `crossover = jsp.pr`:
the two children are two points of the path between the elite partner and
the mutated copy of the food source in the space of relative orders of
operations: each operation takes the key (1 - a) posA + a posB and the child
is the operations sorted by key, for a = 1/3 and 2/3, fixed in advance. Pairs
both parents order alike keep their order.

Where it comes from. TS/PR is the method behind many of the recent Taillard
upper bounds. H-2 (IPRTS, branch experiment/path-relinking) failed with a
walk over extreme critical arcs that returned the BEST point of the walk,
which stays next to its start, and with the shallow kernel of the time. Here
the point is taken at a fixed distance from both parents, and the chain that
starts from it is I-021's deep one. A first version walked by swapping
differing positions, which scrambles the relative order of a job sequence; the
pre-launch check caught it (ta23 1663 against 1573) before any filter ran.

The filter uses seeds 1001 to 1030, outside the waves' 1 to 30. One run per
job, one results directory per job.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXPERIMENT = os.path.abspath(os.path.join(HERE, "..", ".."))
# From I-019 on the control is the configuration I-018 made current
BASE = os.path.join(EXPERIMENT, "setup", "ref_I-021.txt")

FILTER_RUNS = 30
FILTER_FIRST_SEED = 1001      # outside the waves' seeds 1..30
WAVE_RUNS = 5
CHUNK = 1
WAVES = 6

BUDGET = {"20x20": 40, "30x15": 100, "30x20": 150}
SIZE = {}
for row in open(os.path.join(EXPERIMENT, "taillard_bounds.csv")):
    f = row.strip().split(",")
    if f[0] != "instance":
        SIZE[f[0]] = f[1] + "x" + f[2]

FULL = ["ta22", "ta23", "ta25", "ta26", "ta27", "ta29", "ta30", "ta32", "ta33",
        "ta34", "ta40", "ta41", "ta42", "ta43", "ta44", "ta45", "ta46", "ta47",
        "ta48", "ta49", "ta50"]
FILTER = ["ta29", "ta30", "ta23", "ta45"]
CELLS = ["control", "pr"]


def setup_text(instance, cell, runs, seed, tag):
    out = []
    for line in open(BASE).read().splitlines():
        if line.startswith("timelimit = "):
            line = "timelimit = %d" % BUDGET[SIZE[instance]]
        elif line.startswith("runs = "):
            line = "runs = %d" % runs
        elif line.startswith("seed = "):
            line = "seed = %d" % seed
        elif line.startswith("crossover = ") and cell == "pr":
            out.append("# I-036: path relinking instead of JOX")
            line = "crossover = jsp.pr"
        out.append(line)
    header = ("# GENERATED by iter/I-036/make_jobs.py, cell %s, %s, %s\n"
              "# (%s, %d s per run, %d runs, seed %d). Do not edit.\n"
              % (cell, instance, tag, SIZE[instance], BUDGET[SIZE[instance]],
                 runs, seed))
    return header + "\n".join(out) + "\n"


def write(instances, total_runs, first_seed, tag):
    setup_dir = os.path.join(HERE, "setups")
    os.makedirs(setup_dir, exist_ok=True)
    jobs = []
    for instance in instances:
        for cell in CELLS:
            done = 0
            piece = 0
            while done < total_runs:
                piece += 1
                runs = min(CHUNK, total_runs - done)
                seed = first_seed + done
                name = "%s_%s_%s_p%02d" % (instance, cell, tag, piece)
                path = os.path.join(setup_dir, name + ".txt")
                with open(path, "w", newline="\n") as handle:
                    handle.write(setup_text(instance, cell, runs, seed, tag))
                # One results directory per chunk: the solver names its output
                # by a one-second timestamp, so two concurrent jobs on the same
                # instance in one directory overwrite each other (I-011).
                jobs.append("%s\tI-036_%s_p%02d_%s\t%s"
                            % (path, tag, piece, cell, instance))
                done += runs
    jobs_path = os.path.join(HERE, "jobs_%s.tsv" % tag)
    with open(jobs_path, "w", newline="\n") as handle:
        handle.write("# I-036 %s: %d instances x %d cells x %d runs, one run per job\n"
                     % (tag, len(instances), len(CELLS), total_runs))
        handle.write("\n".join(jobs) + "\n")
    cpu = sum(BUDGET[SIZE[i]] * total_runs * len(CELLS) for i in instances)
    print("%s: %d jobs -> %s  (%.1f CPU-hours)"
          % (tag, len(jobs), os.path.relpath(jobs_path), cpu / 3600.0))


def main():
    which = sys.argv[1] if len(sys.argv) > 1 else ""
    if which == "filter":
        write(FILTER, FILTER_RUNS, FILTER_FIRST_SEED, "filter")
    elif which == "wave":
        try:
            n = int(sys.argv[2])
        except (IndexError, ValueError):
            raise SystemExit(__doc__)
        if not 1 <= n <= WAVES:
            raise SystemExit("wave must be 1..%d" % WAVES)
        write(FULL, WAVE_RUNS, 1 + WAVE_RUNS * (n - 1), "w%d" % n)
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    main()
