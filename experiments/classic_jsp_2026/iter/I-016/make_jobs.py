#!/usr/bin/env python3
"""I-016: the PI's circle seeding, and the random creation made uniform.

Usage: make_jobs.py filter
       make_jobs.py wave <N>        with N in 1..6; the cells are those
                                    listed in wave_cells.txt, written when
                                    the filter is decided

Three cells:

`control`  the frozen configuration.
`circle`   the PI's idea (2026-09-23). Picture the whole space of solutions as
           a circle, cut it into 247 equal arcs, let each cut be one solution
           of the initial population, and rotate the circle for every seed so
           the selection never repeats. Realised exactly: the operation
           sequences are numbered in lexicographic order, 0..|S|-1 with
           |S| = (nm)!/(m!)^n (about 10^500 for 20x20), and circle g places its
           247 points at o_g + floor(k |S| / 247), the rotation o_g being the
           golden-ratio fraction of one arc (scripts/circle_pool.py). Run g
           reads circle g through the seeded creation. The scouts keep the
           frozen random creation.
`uniform`  creation.random.draw = uniform: the random creation draws each job in
           proportion to its remaining operations, so every sequence is equally
           likely. This touches the first population AND the scouts, 500 to
           800 draws a run.

What was measured before launching (2026-09-23), and it shapes how the result
has to be read:
* Coverage. For 4000 random probe sequences, the distance to the nearest of
  247 seeds: circle 0.9169 against random 0.9168 on ta23, 0.9443 against
  0.9443 on ta45. In a space of 10^500 points no 247 of them cover anything,
  however they are placed, and the circle covers exactly as random does.
* Generation 0, after decoding. The circle starts at an average makespan of
  about 2127 on ta23 and 2754 on ta45 against the frozen creation's 2269 and
  2952; but uniformly random sequences through the same seeded path start at
  2117 and 2753. The gain is not the circle: the frozen random creation is
  biased, drawing uniformly among the jobs with operations left, so the tail of
  each sequence fills with the last operations of a few jobs left behind.
  Hence the third cell.
* Against both, I-001: a 294-unit head start at generation 0 survived as 0.9
  units at the end. Here the head start is 140 to 200.

Both treated cells are compared with the control; see analyze.py for the
boundary when both reach the waves. One run per job, one results directory per
job.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXPERIMENT = os.path.abspath(os.path.join(HERE, "..", ".."))
BASE = os.path.join(EXPERIMENT, "setup", "prereg2_abc_300s.txt")
POOLS = os.path.join(EXPERIMENT, "seeds", "circle")

FILTER_RUNS = 30
WAVE_RUNS = 5
CHUNK = 1
WAVES = 6

BUDGET = {"20x20": 40, "30x15": 100, "30x20": 150}
SIZE = {}
for row in open(os.path.join(EXPERIMENT, "taillard_bounds.csv")):
    f = row.strip().split(",")
    if f[0] != "instance":
        SIZE[f[0]] = f[1] + "x" + f[2]

FULL = ["ta22", "ta23", "ta25", "ta26", "ta27", "ta29", "ta30", "ta32", "ta33",
        "ta34", "ta40", "ta41", "ta42", "ta43", "ta44", "ta45", "ta46", "ta47",
        "ta48", "ta49", "ta50"]
FILTER = ["ta29", "ta30", "ta23", "ta45"]
CELLS = ["control", "circle", "uniform"]


def wave_cells():
    path = os.path.join(HERE, "wave_cells.txt")
    if not os.path.isfile(path):
        raise SystemExit("wave_cells.txt is written when the filter is decided")
    cells = [c.strip() for c in open(path) if c.strip() and not c.startswith("#")]
    assert cells[0] == "control" and set(cells) <= set(CELLS), cells
    return cells


def setup_text(instance, cell, runs, seed, tag):
    out = []
    for line in open(BASE).read().splitlines():
        if line.startswith("timelimit = "):
            line = "timelimit = %d" % BUDGET[SIZE[instance]]
        elif line.startswith("runs = "):
            line = "runs = %d" % runs
        elif line.startswith("seed = "):
            line = "seed = %d" % seed
        elif line.startswith("creation = ") and cell == "circle":
            line = "creation = jsp.seeded"
        out.append(line)
    if cell == "circle":
        pool = os.path.join(POOLS, instance + ".csv")
        if not os.path.isfile(pool):
            raise SystemExit("missing circle pool %s" % pool)
        out += ["", "# I-016: the first population is circle g = seed - 1",
                "creation.seed.pool = %s" % pool,
                "creation.seed.count = 247",
                "creation.seed.offset = %d" % (seed - 1)]
    elif cell == "uniform":
        out += ["", "# I-016: every sequence equally likely, first population and scouts",
                "creation.random.draw = uniform"]
    header = ("# GENERATED by iter/I-016/make_jobs.py, cell %s, %s, %s\n"
              "# (%s, %d s per run, %d runs, seed %d). Do not edit.\n"
              % (cell, instance, tag, SIZE[instance], BUDGET[SIZE[instance]],
                 runs, seed))
    return header + "\n".join(out) + "\n"


def write(instances, cells, total_runs, first_seed, tag):
    setup_dir = os.path.join(HERE, "setups")
    os.makedirs(setup_dir, exist_ok=True)
    jobs = []
    for instance in instances:
        for cell in cells:
            done = piece = 0
            while done < total_runs:
                piece += 1
                runs = min(CHUNK, total_runs - done)
                seed = first_seed + done
                name = "%s_%s_%s_p%02d" % (instance, cell, tag, piece)
                path = os.path.join(setup_dir, name + ".txt")
                with open(path, "w", newline="\n") as handle:
                    handle.write(setup_text(instance, cell, runs, seed, tag))
                # one results directory per job (I-011)
                jobs.append("%s\tI-016_%s_p%02d_%s\t%s"
                            % (path, tag, piece, cell, instance))
                done += runs
    jobs_path = os.path.join(HERE, "jobs_%s.tsv" % tag)
    with open(jobs_path, "w", newline="\n") as handle:
        handle.write("# I-016 %s: %d instances x %d cells x %d runs, one run per job\n"
                     % (tag, len(instances), len(cells), total_runs))
        handle.write("\n".join(jobs) + "\n")
    cpu = sum(BUDGET[SIZE[i]] * total_runs * len(cells) for i in instances)
    print("%s: %d jobs -> %s  (%.1f CPU-hours)"
          % (tag, len(jobs), os.path.relpath(jobs_path), cpu / 3600.0))


def main():
    which = sys.argv[1] if len(sys.argv) > 1 else ""
    if which == "filter":
        write(FILTER, CELLS, FILTER_RUNS, 1, "filter")
    elif which == "wave":
        try:
            n = int(sys.argv[2])
        except (IndexError, ValueError):
            raise SystemExit(__doc__)
        if not 1 <= n <= WAVES:
            raise SystemExit("wave must be 1..%d" % WAVES)
        write(FULL, wave_cells(), WAVE_RUNS, 1 + WAVE_RUNS * (n - 1), "w%d" % n)
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    main()
