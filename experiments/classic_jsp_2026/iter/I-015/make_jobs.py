#!/usr/bin/env python3
"""I-015: lift the plateau veto.

Usage: make_jobs.py filter
       make_jobs.py wave <N>        with N in 1..6

Two cells. `control` is the frozen configuration, where an offspring that
improves its individual up to EXACTLY the incumbent's makespan is discarded
and counted as a failed trial, both in the crossover replacement and in the
Lamarckian write-back of the tabu search. `allow` sets abc.plateau = allow and
keeps it like any other improvement. No numeric parameter.

The veto is a duplicate filter built on the fitness rather than the genotype:
it rejects different solutions for tying with the incumbent and admits clones
whose makespan differs. In JSP the plateaus at the incumbent's value are large,
and moving sideways along them is how a search leaves a basin, which is exactly
what I-015 found this one cannot do. Measured before: 1,324 improvements per
run discarded in the write-back on ta29 and 3,415 on ta41, 2.4 % of the useful
tabu work, spread 71 to 8,073 between runs. The pre-launch check shows the
switch turning 1,304 + 93 vetoes into 1,898 + 287 admissions on ta29.

The risk runs the other way and is declared in advance: the veto may be doing
real work as a crude duplicate filter, and without it the population can fill
with incumbent-valued solutions and lose diversity.

Both cells are chunked one run per job, so neither sets the wall clock.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXPERIMENT = os.path.abspath(os.path.join(HERE, "..", ".."))
BASE = os.path.join(EXPERIMENT, "setup", "prereg2_abc_300s.txt")

FILTER_RUNS = 30
WAVE_RUNS = 5
CHUNK = 1
WAVES = 6

BUDGET = {"20x20": 40, "30x15": 100, "30x20": 150}
SIZE = {}
for row in open(os.path.join(EXPERIMENT, "taillard_bounds.csv")):
    f = row.strip().split(",")
    if f[0] != "instance":
        SIZE[f[0]] = f[1] + "x" + f[2]

FULL = ["ta22", "ta23", "ta25", "ta26", "ta27", "ta29", "ta30", "ta32", "ta33",
        "ta34", "ta40", "ta41", "ta42", "ta43", "ta44", "ta45", "ta46", "ta47",
        "ta48", "ta49", "ta50"]
FILTER = ["ta29", "ta30", "ta23", "ta45"]
CELLS = ["control", "allow"]


def setup_text(instance, cell, runs, seed, tag):
    out = []
    for line in open(BASE).read().splitlines():
        if line.startswith("timelimit = "):
            line = "timelimit = %d" % BUDGET[SIZE[instance]]
        elif line.startswith("runs = "):
            line = "runs = %d" % runs
        elif line.startswith("seed = "):
            line = "seed = %d" % seed
        out.append(line)
    if cell == "allow":
        out.append("")
        out.append("# I-015: keep improvements that land exactly on the incumbent")
        out.append("abc.plateau = allow")
    header = ("# GENERATED by iter/I-015/make_jobs.py, cell %s, %s, %s\n"
              "# (%s, %d s per run, %d runs, seed %d). Do not edit.\n"
              % (cell, instance, tag, SIZE[instance], BUDGET[SIZE[instance]],
                 runs, seed))
    return header + "\n".join(out) + "\n"


def write(instances, total_runs, first_seed, tag):
    setup_dir = os.path.join(HERE, "setups")
    os.makedirs(setup_dir, exist_ok=True)
    jobs = []
    for instance in instances:
        for cell in CELLS:
            done = 0
            piece = 0
            while done < total_runs:
                piece += 1
                runs = min(CHUNK, total_runs - done)
                seed = first_seed + done
                name = "%s_%s_%s_p%02d" % (instance, cell, tag, piece)
                path = os.path.join(setup_dir, name + ".txt")
                with open(path, "w", newline="\n") as handle:
                    handle.write(setup_text(instance, cell, runs, seed, tag))
                # One results directory per chunk: the solver names its output
                # by a one-second timestamp, so two concurrent jobs on the same
                # instance in one directory overwrite each other (I-011).
                jobs.append("%s\tI-015_%s_p%02d_%s\t%s"
                            % (path, tag, piece, cell, instance))
                done += runs
    jobs_path = os.path.join(HERE, "jobs_%s.tsv" % tag)
    with open(jobs_path, "w", newline="\n") as handle:
        handle.write("# I-015 %s: %d instances x %d cells x %d runs, one run per job\n"
                     % (tag, len(instances), len(CELLS), total_runs))
        handle.write("\n".join(jobs) + "\n")
    cpu = sum(BUDGET[SIZE[i]] * total_runs * len(CELLS) for i in instances)
    print("%s: %d jobs -> %s  (%.1f CPU-hours)"
          % (tag, len(jobs), os.path.relpath(jobs_path), cpu / 3600.0))


def main():
    which = sys.argv[1] if len(sys.argv) > 1 else ""
    if which == "filter":
        write(FILTER, FILTER_RUNS, 1, "filter")
    elif which == "wave":
        try:
            n = int(sys.argv[2])
        except (IndexError, ValueError):
            raise SystemExit(__doc__)
        if not 1 <= n <= WAVES:
            raise SystemExit("wave must be 1..%d" % WAVES)
        write(FULL, WAVE_RUNS, 1 + WAVE_RUNS * (n - 1), "w%d" % n)
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    main()
