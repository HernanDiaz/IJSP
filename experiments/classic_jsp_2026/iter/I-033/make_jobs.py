#!/usr/bin/env python3
"""I-033: a record hunt on ta18, the one open instance this line never touched.

Usage: make_jobs.py hunt

taillard_bounds.csv lists ta18 (20x15) as open: best known 1396, lower bound
1377, 19 units of room. It is outside the protocol's list of 21 because the
lists were drawn for 20x20 and larger. It is small, so short runs go far, and
a hunt costs twenty minutes. A 20x15 instance this studied is unlikely to fall;
this is declared, and the hunt is cheap enough to run anyway.

There is no per-class budget for 20x15; 40 s per run, the 20x20 budget, is
declared here and no per-class budget is touched. One cell, the current
configuration, 400 runs on fresh seeds 9001 to 9400. A record is proved by its
schedule.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXPERIMENT = os.path.abspath(os.path.join(HERE, "..", ".."))
BASE = os.path.join(EXPERIMENT, "setup", "ref_I-021.txt")

INSTANCES = ["ta18"]
RUNS_TOTAL = 400
RUNS_PER_JOB = 5
FIRST_SEED = 9001
BUDGET = 40


def setup_text(instance, runs, seed, tag):
    out = []
    for line in open(BASE).read().splitlines():
        if line.startswith("timelimit = "):
            line = "timelimit = %d" % BUDGET
        elif line.startswith("runs = "):
            line = "runs = %d" % runs
        elif line.startswith("seed = "):
            line = "seed = %d" % seed
        out.append(line)
    header = ("# GENERATED by iter/I-033/make_jobs.py, %s, %s (%d s per run, %d "
              "runs, seed %d). Do not edit.\n" % (instance, tag, BUDGET, runs, seed))
    return header + "\n".join(out) + "\n"


def main():
    if (sys.argv[1:2] or [""])[0] != "hunt":
        raise SystemExit(__doc__)
    setup_dir = os.path.join(HERE, "setups")
    os.makedirs(setup_dir, exist_ok=True)
    jobs = []
    for chunk in range(1, RUNS_TOTAL // RUNS_PER_JOB + 1):
        seed = FIRST_SEED + RUNS_PER_JOB * (chunk - 1)
        tag = "c%03d" % chunk
        for instance in INSTANCES:
            path = os.path.join(setup_dir, "%s_%s.txt" % (instance, tag))
            with open(path, "w", newline="\n") as handle:
                handle.write(setup_text(instance, RUNS_PER_JOB, seed, tag))
            # one results directory per chunk; the two instances in it write
            # files named by instance, so they cannot collide
            jobs.append("%s\tI-033_%s\t%s" % (path, tag, instance))
    with open(os.path.join(HERE, "jobs_hunt.tsv"), "w", newline="\n") as handle:
        handle.write("# I-033 hunt: %s, %d runs each of %d s, seeds %d..%d\n"
                     % (" ".join(INSTANCES), RUNS_TOTAL, BUDGET, FIRST_SEED,
                        FIRST_SEED + RUNS_TOTAL - 1))
        handle.write("\n".join(jobs) + "\n")
    print("hunt: %d jobs, %d runs, %.1f CPU-hours"
          % (len(jobs), len(jobs) * RUNS_PER_JOB,
             len(jobs) * RUNS_PER_JOB * BUDGET / 3600.0))


if __name__ == "__main__":
    main()
