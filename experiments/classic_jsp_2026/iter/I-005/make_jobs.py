#!/usr/bin/env python3
"""I-005: write the setups and the job list for the filter or for one wave.

Usage: make_jobs.py filter
       make_jobs.py wave <N>        with N in 1..6

Two cells. `control` is the frozen ABC, behaviourally identical to the
controls of I-001, I-002 and I-003. `fulltails` adds one line:

    localsearch.tails = full

which rebuilds every tail before each estimation of the N2 neighbourhood
instead of relying on the incremental sweep of acceptNeighbour. Algorithm
parameters stay frozen at irace's configuration 136; this changes no
parameter, it repairs the data the neighbourhood is sorted and pruned with.

Both stages are chunked so no single job runs much longer than 13 minutes,
per "Cadencia" in RESEARCH_IDEAS.md.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXPERIMENT = os.path.abspath(os.path.join(HERE, "..", ".."))
BASE = os.path.join(EXPERIMENT, "setup", "prereg2_abc_300s.txt")

FILTER_RUNS = 30
FILTER_CHUNKS = 6
WAVE_RUNS = 5
WAVES = 6

BUDGET = {"20x20": 40, "30x15": 100, "30x20": 150}
SIZE = {}
for row in open(os.path.join(EXPERIMENT, "taillard_bounds.csv")):
    f = row.strip().split(",")
    if f[0] != "instance":
        SIZE[f[0]] = f[1] + "x" + f[2]

FULL = ["ta22", "ta23", "ta25", "ta26", "ta27", "ta29", "ta30", "ta32", "ta33",
        "ta34", "ta40", "ta41", "ta42", "ta43", "ta44", "ta45", "ta46", "ta47",
        "ta48", "ta49", "ta50"]
FILTER = ["ta29", "ta30", "ta23", "ta45"]          # fixed in RESEARCH_IDEAS.md
CELLS = ["control", "freqtie"]


def setup_text(instance, cell, runs, seed, tag):
    out = []
    for line in open(BASE).read().splitlines():
        if line.startswith("timelimit = "):
            line = "timelimit = %d" % BUDGET[SIZE[instance]]
        elif line.startswith("runs = "):
            line = "runs = %d" % runs
        elif line.startswith("seed = "):
            line = "seed = %d" % seed
        out.append(line)
    if cell == "freqtie":
        out.append("")
        out.append("# I-005: rebuild every tail before each estimation, so the")
        out.append("# heads&tails estimate is the lower bound it is meant to be.")
        out.append("localsearch.tails = full")
    header = ("# GENERATED by iter/I-005/make_jobs.py, cell %s, %s, %s\n"
              "# (%s, %d s per run, %d runs, seed %d). Do not edit.\n"
              % (cell, instance, tag, SIZE[instance],
                 BUDGET[SIZE[instance]], runs, seed))
    return header + "\n".join(out) + "\n"


def write(instances, runs, seed, tag):
    setup_dir = os.path.join(HERE, "setups")
    os.makedirs(setup_dir, exist_ok=True)
    jobs = []
    for instance in instances:
        for cell in CELLS:
            path = os.path.join(setup_dir, "%s_%s_%s.txt" % (instance, cell, tag))
            with open(path, "w", newline="\n") as handle:
                handle.write(setup_text(instance, cell, runs, seed, tag))
            jobs.append("%s\tI-005_%s_%s\t%s" % (path, tag, cell, instance))
    jobs_path = os.path.join(HERE, "jobs_%s.tsv" % tag)
    with open(jobs_path, "w", newline="\n") as handle:
        handle.write("# I-005 %s: %d instances x %d cells, %d runs each, seed %d\n"
                     % (tag, len(instances), len(CELLS), runs, seed))
        handle.write("\n".join(jobs) + "\n")
    cpu = sum(BUDGET[SIZE[i]] * runs * len(CELLS) for i in instances)
    print("%s: %d jobs -> %s  (%.1f CPU-hours)"
          % (tag, len(jobs), os.path.relpath(jobs_path), cpu / 3600.0))
    return jobs_path


def main():
    which = sys.argv[1] if len(sys.argv) > 1 else ""
    if which == "filter":
        runs = FILTER_RUNS // FILTER_CHUNKS
        paths = [write(FILTER, runs, 1 + runs * (c - 1), "fc%d" % c)
                 for c in range(1, FILTER_CHUNKS + 1)]
        combined = os.path.join(HERE, "jobs_filter.tsv")
        with open(combined, "w", newline="\n") as handle:
            handle.write("# I-005 filter: the %d chunks as one queue, "
                         "%d runs per cell and instance, seeds 1..%d\n"
                         % (FILTER_CHUNKS, FILTER_RUNS, FILTER_RUNS))
            for p in paths:
                for line in open(p):
                    if line.strip() and not line.startswith("#"):
                        handle.write(line)
        n = sum(1 for l in open(combined) if l.strip() and not l.startswith("#"))
        print("filter (one queue): %d jobs -> %s" % (n, os.path.relpath(combined)))
    elif which == "wave":
        try:
            n = int(sys.argv[2])
        except (IndexError, ValueError):
            raise SystemExit(__doc__)
        if not 1 <= n <= WAVES:
            raise SystemExit("wave must be 1..%d" % WAVES)
        write(FULL, WAVE_RUNS, 1 + WAVE_RUNS * (n - 1), "w%d" % n)
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    main()
