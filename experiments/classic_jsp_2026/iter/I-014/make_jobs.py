#!/usr/bin/env python3
"""I-014: restart the population around the incumbent when the run stalls.

Usage: make_jobs.py filter
       make_jobs.py wave <N>        with N in 1..6

Two cells. `control` is the frozen configuration. `restart` sets
abc.restart = stall: once 0.2 of the budget has passed with no new global best,
the population is rebuilt from the incumbent plus perturbed copies of it, 1 to
10 mutations each, and the run carries on to the same budget.

Every constant is fixed in advance by a measurement, none is tuned. The 0.2
comes from the stall hazard (scripts/stall_hazard.py, 120 control runs): the
first bin edge at which the hazard falls below a tenth of its value in the
first second, which is 0.10 to 0.20 of the budget across the four instances,
taking the most conservative. The 1-to-10 spread sits below the reach of one
tabu call, measured at 26 to 41 moves, so the perturbation is not simply undone
by the local search that follows it.

The cold form of this idea, rebuilding with the creation operator, was withdrawn
before any machine time was spent: scripts/cold_catchup.py shows a cold
population is still +4.5 to +22 behind at 40 % of the budget and +27 to +55 at
20 %, while a stall restart is handed only what remains after a stall that
begins at a median 0.56 to 0.82 of the budget. It cannot catch up. Rebuilding
around the incumbent costs nothing to catch up, so the thing under test is
diversity rather than a handicap.

Both cells are chunked one run per job, so neither sets the wall clock.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXPERIMENT = os.path.abspath(os.path.join(HERE, "..", ".."))
BASE = os.path.join(EXPERIMENT, "setup", "prereg2_abc_300s.txt")

FILTER_RUNS = 30
WAVE_RUNS = 5
CHUNK = 1
WAVES = 6

BUDGET = {"20x20": 40, "30x15": 100, "30x20": 150}
SIZE = {}
for row in open(os.path.join(EXPERIMENT, "taillard_bounds.csv")):
    f = row.strip().split(",")
    if f[0] != "instance":
        SIZE[f[0]] = f[1] + "x" + f[2]

FULL = ["ta22", "ta23", "ta25", "ta26", "ta27", "ta29", "ta30", "ta32", "ta33",
        "ta34", "ta40", "ta41", "ta42", "ta43", "ta44", "ta45", "ta46", "ta47",
        "ta48", "ta49", "ta50"]
FILTER = ["ta29", "ta30", "ta23", "ta45"]
CELLS = ["control", "restart"]


def setup_text(instance, cell, runs, seed, tag):
    out = []
    for line in open(BASE).read().splitlines():
        if line.startswith("timelimit = "):
            line = "timelimit = %d" % BUDGET[SIZE[instance]]
        elif line.startswith("runs = "):
            line = "runs = %d" % runs
        elif line.startswith("seed = "):
            line = "seed = %d" % seed
        out.append(line)
    if cell == "restart":
        out.append("")
        out.append("# I-014: rebuild the population around the incumbent when the")
        out.append("# run has stalled for 0.2 of its budget")
        out.append("abc.restart = stall")
    header = ("# GENERATED by iter/I-014/make_jobs.py, cell %s, %s, %s\n"
              "# (%s, %d s per run, %d runs, seed %d). Do not edit.\n"
              % (cell, instance, tag, SIZE[instance], BUDGET[SIZE[instance]],
                 runs, seed))
    return header + "\n".join(out) + "\n"


def write(instances, total_runs, first_seed, tag):
    setup_dir = os.path.join(HERE, "setups")
    os.makedirs(setup_dir, exist_ok=True)
    jobs = []
    for instance in instances:
        for cell in CELLS:
            done = 0
            piece = 0
            while done < total_runs:
                piece += 1
                runs = min(CHUNK, total_runs - done)
                seed = first_seed + done
                name = "%s_%s_%s_p%02d" % (instance, cell, tag, piece)
                path = os.path.join(setup_dir, name + ".txt")
                with open(path, "w", newline="\n") as handle:
                    handle.write(setup_text(instance, cell, runs, seed, tag))
                # One results directory per chunk: the solver names its output
                # by a one-second timestamp, so two concurrent jobs on the same
                # instance in one directory overwrite each other (I-011).
                jobs.append("%s\tI-014_%s_p%02d_%s\t%s"
                            % (path, tag, piece, cell, instance))
                done += runs
    jobs_path = os.path.join(HERE, "jobs_%s.tsv" % tag)
    with open(jobs_path, "w", newline="\n") as handle:
        handle.write("# I-014 %s: %d instances x %d cells x %d runs, one run per job\n"
                     % (tag, len(instances), len(CELLS), total_runs))
        handle.write("\n".join(jobs) + "\n")
    cpu = sum(BUDGET[SIZE[i]] * total_runs * len(CELLS) for i in instances)
    print("%s: %d jobs -> %s  (%.1f CPU-hours)"
          % (tag, len(jobs), os.path.relpath(jobs_path), cpu / 3600.0))


def main():
    which = sys.argv[1] if len(sys.argv) > 1 else ""
    if which == "filter":
        write(FILTER, FILTER_RUNS, 1, "filter")
    elif which == "wave":
        try:
            n = int(sys.argv[2])
        except (IndexError, ValueError):
            raise SystemExit(__doc__)
        if not 1 <= n <= WAVES:
            raise SystemExit("wave must be 1..%d" % WAVES)
        write(FULL, WAVE_RUNS, 1 + WAVE_RUNS * (n - 1), "w%d" % n)
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    main()
