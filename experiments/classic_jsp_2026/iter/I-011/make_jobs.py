#!/usr/bin/env python3
"""I-011 [TAIL]: a portfolio of the switches the loop has measured neutral.

Usage: make_jobs.py filter
       make_jobs.py wave <N>        with N in 1..6

Two cells. `control` is the frozen configuration. `portfolio` spends its runs
across the 16 combinations of four binary switches, every one of them
implemented by an earlier iteration, verified to execute, and **confirmed
mean-neutral over the 21 open instances with its own boundary**:

    bit 0  creation = jsp.seeded, pool mix, k = 25     I-001, p = 0.348
    bit 1  localsearch.tails = full                    I-004, p = 0.677
    bit 2  abc.scout = kick, 3 kicks                   I-003, four flat looks
    bit 3  localsearch.deadend = escape                I-012, p = 0.835

A mixture of mean-neutral components is mean-neutral, and its variance is the
within-component variance plus the between-component variance, so its lower
tail is longer by construction. That is the hypothesis, and it is why this is
declared a TAIL iteration: the endpoint is the mean of the bests over blocks
of five, the mean may worsen, and the filter rule applies to the tail.

The portfolio is a job-generation matter and touches no solver code. Each of
its chunks carries one combination; the control's runs are chunked normally.
Both cells run the same number of runs on the same instances at the same
budget, and the queue interleaves them, so machine drift hits both alike.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXPERIMENT = os.path.abspath(os.path.join(HERE, "..", ".."))
BASE = os.path.join(EXPERIMENT, "setup", "prereg2_abc_300s.txt")
SEEDS = os.path.join(EXPERIMENT, "seeds")

FILTER_RUNS = 30
FILTER_CHUNK = 2            # so each filter chunk can carry its own combination
WAVE_RUNS = 5
WAVE_CHUNK = 1              # a wave gives the portfolio five combinations
WAVES = 6
COMBINATIONS = 16
SEED_COUNT = 25

BUDGET = {"20x20": 40, "30x15": 100, "30x20": 150}
SIZE = {}
for row in open(os.path.join(EXPERIMENT, "taillard_bounds.csv")):
    f = row.strip().split(",")
    if f[0] != "instance":
        SIZE[f[0]] = f[1] + "x" + f[2]

FULL = ["ta22", "ta23", "ta25", "ta26", "ta27", "ta29", "ta30", "ta32", "ta33",
        "ta34", "ta40", "ta41", "ta42", "ta43", "ta44", "ta45", "ta46", "ta47",
        "ta48", "ta49", "ta50"]
FILTER = ["ta29", "ta30", "ta23", "ta45"]
CELLS = ["control", "portfolio"]


def switch_lines(combination, instance):
    """The setup lines of one of the 16 combinations."""
    out = []
    if combination & 1:
        pool = os.path.join(SEEDS, "%s_mix.csv" % instance)
        if not os.path.isfile(pool):
            raise SystemExit("missing pool %s" % pool)
        out += ["creation = jsp.seeded",
                "creation.seed.pool = %s" % pool,
                "creation.seed.count = %d" % SEED_COUNT]
    if combination & 2:
        out += ["localsearch.tails = full"]
    if combination & 4:
        out += ["abc.scout = kick", "abc.scout.kicks = 3"]
    if combination & 8:
        out += ["localsearch.deadend = escape"]
    return out


def setup_text(instance, cell, runs, seed, tag, combination):
    out = []
    for line in open(BASE).read().splitlines():
        if line.startswith("timelimit = "):
            line = "timelimit = %d" % BUDGET[SIZE[instance]]
        elif line.startswith("runs = "):
            line = "runs = %d" % runs
        elif line.startswith("seed = "):
            line = "seed = %d" % seed
        elif line.startswith("creation = ") and cell == "portfolio" and (combination & 1):
            continue          # replaced below
        out.append(line)
    if cell == "portfolio":
        lines = switch_lines(combination, instance)
        out.append("")
        out.append("# I-011, portfolio combination %d of %d: %s"
                   % (combination, COMBINATIONS - 1,
                      ", ".join(lines) if lines else "none, the frozen configuration"))
        out += lines
    header = ("# GENERATED by iter/I-011/make_jobs.py, cell %s, %s, %s\n"
              "# (%s, %d s per run, %d runs, seed %d%s). Do not edit.\n"
              % (cell, instance, tag, SIZE[instance], BUDGET[SIZE[instance]],
                 runs, seed,
                 ", combination %d" % combination if cell == "portfolio" else ""))
    return header + "\n".join(out) + "\n"


def write(instances, total_runs, chunk, first_seed, tag, combination_base):
    setup_dir = os.path.join(HERE, "setups")
    os.makedirs(setup_dir, exist_ok=True)
    jobs = []
    for instance in instances:
        for cell in CELLS:
            done = 0
            piece = 0
            step = chunk if cell == "portfolio" else total_runs
            while done < total_runs:
                piece += 1
                runs = min(step, total_runs - done)
                seed = first_seed + done
                combination = (combination_base + piece - 1) % COMBINATIONS
                name = "%s_%s_%s_p%02d" % (instance, cell, tag, piece)
                path = os.path.join(setup_dir, name + ".txt")
                with open(path, "w", newline="\n") as handle:
                    handle.write(setup_text(instance, cell, runs, seed, tag, combination))
                jobs.append("%s\tI-011_%s_%s\t%s" % (path, tag, cell, instance))
                done += runs
    jobs_path = os.path.join(HERE, "jobs_%s.tsv" % tag)
    with open(jobs_path, "w", newline="\n") as handle:
        handle.write("# I-011 %s: %d instances x %d cells x %d runs; the portfolio\n"
                     "# cell carries one of %d combinations per chunk of %d runs\n"
                     % (tag, len(instances), len(CELLS), total_runs,
                        COMBINATIONS, chunk))
        handle.write("\n".join(jobs) + "\n")
    cpu = sum(BUDGET[SIZE[i]] * total_runs * len(CELLS) for i in instances)
    print("%s: %d jobs -> %s  (%.1f CPU-hours)"
          % (tag, len(jobs), os.path.relpath(jobs_path), cpu / 3600.0))
    return jobs_path


def main():
    which = sys.argv[1] if len(sys.argv) > 1 else ""
    if which == "filter":
        write(FILTER, FILTER_RUNS, FILTER_CHUNK, 1, "filter", 0)
    elif which == "wave":
        try:
            n = int(sys.argv[2])
        except (IndexError, ValueError):
            raise SystemExit(__doc__)
        if not 1 <= n <= WAVES:
            raise SystemExit("wave must be 1..%d" % WAVES)
        write(FULL, WAVE_RUNS, WAVE_CHUNK, 1 + WAVE_RUNS * (n - 1),
              "w%d" % n, (n - 1) * WAVE_RUNS)
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    main()
