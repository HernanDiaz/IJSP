#!/usr/bin/env python3
"""I-019: a record attempt with the configuration I-018 made current.

Usage: make_jobs.py attempt

The objective of the line is to beat or match a best known solution, and a
record is proved by its schedule, not by a p-value, so there is no filter and
no wave structure: nothing is accepted or rejected here.

I-018 is the loop's first accepted mechanism: the second tabu call of each pair
of children always searches the better child again, -3.38 on the per-instance
mean over the 21 open instances, and best-of-five moved -4.19 with it. A shift
of the mean is not a record; records live in the lower tail. This batch spends
its runs where our best is closest to the best known, with the new
configuration, and keeps the old one alongside so the attempt doubles as a
measurement of whether the accepted gain reaches the tail.

Two cells. `control` is prereg2, the configuration before I-018. `best` is
setup/ref_I-018.txt, prereg2 plus abc.ls.pick = best. Same short list, same 75
runs of 40 s per cell and instance as I-019, on FRESH seeds 2001 to 2075, which
no earlier batch has used.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXPERIMENT = os.path.abspath(os.path.join(HERE, "..", ".."))
BASE = os.path.join(EXPERIMENT, "setup", "prereg2_abc_300s.txt")
REFERENCE = os.path.join(EXPERIMENT, "setup", "ref_I-018.txt")
FIRST_SEED = 2001          # fresh: no earlier batch has used these

RUNS_TOTAL = 75            # per instance and cell
RUNS_PER_JOB = 5           # so no job runs longer than about 13 minutes
BUDGET = {"20x20": 40, "30x15": 100, "30x20": 150}

SIZE = {}
BKS = {}
for row in open(os.path.join(EXPERIMENT, "taillard_bounds.csv")):
    f = row.strip().split(",")
    if f[0] != "instance":
        SIZE[f[0]] = f[1] + "x" + f[2]

# The shortlist: the instances where our best verified makespan is closest to
# the BKS (JOURNAL 2026-09-21). ta29 was matched once at 1625 in the long
# regime; ta30 is 11 away in this one.
SHORTLIST = ["ta29", "ta30", "ta23", "ta22"]
CELLS = ["control", "best"]


def setup_text(instance, cell, runs, seed, tag):
    out = []
    for line in open(REFERENCE if cell == "best" else BASE).read().splitlines():
        if line.startswith("timelimit = "):
            line = "timelimit = %d" % BUDGET[SIZE[instance]]
        elif line.startswith("runs = "):
            line = "runs = %d" % runs
        elif line.startswith("seed = "):
            line = "seed = %d" % seed
        out.append(line)
    header = ("# GENERATED by iter/I-019/make_jobs.py, cell %s, %s, %s\n"
              "# (%s, %d s per run, %d runs, seed %d). Do not edit.\n"
              % (cell, instance, tag, SIZE[instance],
                 BUDGET[SIZE[instance]], runs, seed))
    return header + "\n".join(out) + "\n"


def main():
    if (sys.argv[1:2] or [""])[0] != "attempt":
        raise SystemExit(__doc__)
    setup_dir = os.path.join(HERE, "setups")
    os.makedirs(setup_dir, exist_ok=True)
    chunks = RUNS_TOTAL // RUNS_PER_JOB
    jobs = []
    for chunk in range(1, chunks + 1):
        seed = FIRST_SEED + RUNS_PER_JOB * (chunk - 1)
        for instance in SHORTLIST:
            for cell in CELLS:
                tag = "c%02d" % chunk
                path = os.path.join(setup_dir, "%s_%s_%s.txt" % (instance, cell, tag))
                with open(path, "w", newline="\n") as handle:
                    handle.write(setup_text(instance, cell, RUNS_PER_JOB, seed, tag))
                jobs.append("%s\tI-019_%s_%s\t%s" % (path, tag, cell, instance))
    jobs_path = os.path.join(HERE, "jobs_attempt.tsv")
    with open(jobs_path, "w", newline="\n") as handle:
        handle.write("# I-019 record attempt: %d instances x %d cells x %d runs, "
                     "in %d chunks of %d, seeds 1..%d\n"
                     % (len(SHORTLIST), len(CELLS), RUNS_TOTAL,
                        chunks, RUNS_PER_JOB, RUNS_TOTAL))
        handle.write("\n".join(jobs) + "\n")
    cpu = sum(BUDGET[SIZE[i]] * RUNS_TOTAL * len(CELLS) for i in SHORTLIST)
    print("attempt: %d jobs -> %s  (%.1f CPU-hours, %d runs in total)"
          % (len(jobs), os.path.relpath(jobs_path), cpu / 3600.0,
             RUNS_TOTAL * len(CELLS) * len(SHORTLIST)))


if __name__ == "__main__":
    main()
