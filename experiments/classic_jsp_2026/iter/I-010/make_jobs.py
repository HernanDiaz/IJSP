#!/usr/bin/env python3
"""I-010: write the setups and the job list for the filter or for one wave.

Usage: make_jobs.py filter
       make_jobs.py wave <N>        with N in 1..6

Two cells. `control` is the frozen ABC, behaviourally identical to the
controls of I-001 through I-005. `deep` adds one line:

    abc.deepls = 10

which fires a single deep tabu call on the incumbent the first time the run
passes ten generations without improving its global best, with the depth fixed
in advance at 1000 non-improving iterations against the frozen 15, and the
existing 2 s per-call cap left alone. It fires once per run, so the cost is
bounded at about 5 % of a 40 s budget and the comparison at equal wall clock
measures the idea rather than the spend.

Algorithm parameters stay frozen at irace's configuration 136. H-5 closed the
depth as a GLOBAL parameter, since irace swept it from 5 to 40 and chose 15,
but in that space one depth applied to the whole population; the uneven
allocation was never explorable and is what this tests.

Both stages are chunked so no job runs much longer than 13 minutes, per
"Cadencia" in RESEARCH_IDEAS.md.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXPERIMENT = os.path.abspath(os.path.join(HERE, "..", ".."))
BASE = os.path.join(EXPERIMENT, "setup", "prereg2_abc_300s.txt")

FILTER_RUNS = 30
FILTER_CHUNKS = 6
WAVE_RUNS = 5
WAVES = 6
TRIGGER = 10                       # generations of stagnation, fixed in advance

BUDGET = {"20x20": 40, "30x15": 100, "30x20": 150}
SIZE = {}
for row in open(os.path.join(EXPERIMENT, "taillard_bounds.csv")):
    f = row.strip().split(",")
    if f[0] != "instance":
        SIZE[f[0]] = f[1] + "x" + f[2]

FULL = ["ta22", "ta23", "ta25", "ta26", "ta27", "ta29", "ta30", "ta32", "ta33",
        "ta34", "ta40", "ta41", "ta42", "ta43", "ta44", "ta45", "ta46", "ta47",
        "ta48", "ta49", "ta50"]
FILTER = ["ta29", "ta30", "ta23", "ta45"]          # fixed in RESEARCH_IDEAS.md
# Three cells in the filter, because the filter is where variants belong, and
# two in the waves: the confirmation compares the full mechanism only.
CELLS = ["control", "escape", "deepescape"]
# Declared 2026-09-22, after the filter and BEFORE any wave data exists: the
# escape-only cell rides along in the waves as INFORMATION. The primary
# endpoint does not change -- it stays deepescape against control at the
# Pocock boundary -- because the filter's secondary hinting that the escape
# alone is the active ingredient is exactly the kind of thing that must not be
# allowed to redirect a pre-declared decision. Carrying the cell answers the
# question in the same batch at 9.2 CPU-hours a wave instead of 6.1, and
# nothing is inferred from it beyond a reported difference.
WAVE_CELLS = ["control", "escape", "deepescape"]


def setup_text(instance, cell, runs, seed, tag):
    out = []
    for line in open(BASE).read().splitlines():
        if line.startswith("timelimit = "):
            line = "timelimit = %d" % BUDGET[SIZE[instance]]
        elif line.startswith("runs = "):
            line = "runs = %d" % runs
        elif line.startswith("seed = "):
            line = "seed = %d" % seed
        out.append(line)
    if cell in ("escape", "deepescape"):
        out.append("")
        out.append("# I-010: when every neighbour is tabu without aspiring, take the best")
        out.append("# one anyway instead of ending the call. Measured 2026-09-22: every")
        out.append("# deep call died this way after 75 to 92 moves, so this and not")
        out.append("# localsearch.bad-iterations is what caps the depth of the search.")
        out.append("localsearch.deadend = escape")
    if cell == "deepescape":
        out.append("")
        out.append("# ... and spend up to 25 % of the local-search time on deep calls on")
        out.append("# the incumbent, fired while the run has gone %d generations without" % TRIGGER)
        out.append("# improving. With the escape these reach 286 to 1909 moves a call")
        out.append("# instead of 47 to 102, which is the depth the hypothesis is about.")
        out.append("abc.deepls = %d" % TRIGGER)
        out.append("abc.deepls.share = 25")
    header = ("# GENERATED by iter/I-010/make_jobs.py, cell %s, %s, %s\n"
              "# (%s, %d s per run, %d runs, seed %d). Do not edit.\n"
              % (cell, instance, tag, SIZE[instance],
                 BUDGET[SIZE[instance]], runs, seed))
    return header + "\n".join(out) + "\n"


def write(instances, runs, seed, tag, cells=None):
    setup_dir = os.path.join(HERE, "setups")
    os.makedirs(setup_dir, exist_ok=True)
    if cells is None:
        cells = CELLS
    jobs = []
    for instance in instances:
        for cell in cells:
            path = os.path.join(setup_dir, "%s_%s_%s.txt" % (instance, cell, tag))
            with open(path, "w", newline="\n") as handle:
                handle.write(setup_text(instance, cell, runs, seed, tag))
            jobs.append("%s\tI-010_%s_%s\t%s" % (path, tag, cell, instance))
    jobs_path = os.path.join(HERE, "jobs_%s.tsv" % tag)
    with open(jobs_path, "w", newline="\n") as handle:
        handle.write("# I-010 %s: %d instances x %d cells, %d runs each, seed %d\n"
                     % (tag, len(instances), len(cells), runs, seed))
        handle.write("\n".join(jobs) + "\n")
    cpu = sum(BUDGET[SIZE[i]] * runs * len(cells) for i in instances)
    print("%s: %d jobs -> %s  (%.1f CPU-hours)"
          % (tag, len(jobs), os.path.relpath(jobs_path), cpu / 3600.0))
    return jobs_path


def main():
    which = sys.argv[1] if len(sys.argv) > 1 else ""
    if which == "filter":
        runs = FILTER_RUNS // FILTER_CHUNKS
        paths = [write(FILTER, runs, 1 + runs * (c - 1), "fc%d" % c)
                 for c in range(1, FILTER_CHUNKS + 1)]
        combined = os.path.join(HERE, "jobs_filter.tsv")
        with open(combined, "w", newline="\n") as handle:
            handle.write("# I-010 filter: the %d chunks as one queue, "
                         "%d runs per cell and instance, seeds 1..%d\n"
                         % (FILTER_CHUNKS, FILTER_RUNS, FILTER_RUNS))
            for p in paths:
                for line in open(p):
                    if line.strip() and not line.startswith("#"):
                        handle.write(line)
        n = sum(1 for l in open(combined) if l.strip() and not l.startswith("#"))
        print("filter (one queue): %d jobs -> %s" % (n, os.path.relpath(combined)))
    elif which == "wave":
        try:
            n = int(sys.argv[2])
        except (IndexError, ValueError):
            raise SystemExit(__doc__)
        if not 1 <= n <= WAVES:
            raise SystemExit("wave must be 1..%d" % WAVES)
        write(FULL, WAVE_RUNS, 1 + WAVE_RUNS * (n - 1), "w%d" % n, WAVE_CELLS)
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    main()
