#!/usr/bin/env python3
"""I-008: the whole budget on ta29 at 300 s a run.

Usage: make_jobs.py attempt

I-007 measured, at equal total CPU on ta29, that 40 s x 200 runs and 100 s x
80 runs both stop at 1627 while 300 s x 27 runs reaches 1625, the best known
value, and that the three means are indistinguishable. The budget tuned on
the mean is the wrong budget for a record. So this spends everything on the
configuration that has now touched 1625 twice: 84 runs of 300 s, three times
what I-007 gave it.

Fresh seeds, 101 upward, so these are new draws rather than near-repeats of
I-007's 1 to 27.

No filter, no waves, nothing to accept. A record is a makespan strictly below
1625 and its proof is the schedule.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXPERIMENT = os.path.abspath(os.path.join(HERE, "..", ".."))
BASE = os.path.join(EXPERIMENT, "setup", "prereg2_abc_300s.txt")

INSTANCE = "ta29"
SECONDS = 300
RUNS_TOTAL = 84
RUNS_PER_JOB = 2
FIRST_SEED = 101


def setup_text(runs, seed, tag):
    out = []
    for line in open(BASE).read().splitlines():
        if line.startswith("timelimit = "):
            line = "timelimit = %d" % SECONDS
        elif line.startswith("runs = "):
            line = "runs = %d" % runs
        elif line.startswith("seed = "):
            line = "seed = %d" % seed
        out.append(line)
    header = ("# GENERATED by iter/I-008/make_jobs.py, %s, %s\n"
              "# (%d s per run, %d runs, seed %d). Do not edit.\n"
              % (INSTANCE, tag, SECONDS, runs, seed))
    return header + "\n".join(out) + "\n"


def main():
    if (sys.argv[1:2] or [""])[0] != "attempt":
        raise SystemExit(__doc__)
    setup_dir = os.path.join(HERE, "setups")
    os.makedirs(setup_dir, exist_ok=True)
    jobs = []
    done = 0
    chunk = 0
    while done < RUNS_TOTAL:
        chunk += 1
        runs = min(RUNS_PER_JOB, RUNS_TOTAL - done)
        seed = FIRST_SEED + done
        tag = "c%02d" % chunk
        path = os.path.join(setup_dir, "%s_%s.txt" % (INSTANCE, tag))
        with open(path, "w", newline="\n") as handle:
            handle.write(setup_text(runs, seed, tag))
        jobs.append("%s\tI-008_%s\t%s" % (path, tag, INSTANCE))
        done += runs
    jobs_path = os.path.join(HERE, "jobs_attempt.tsv")
    with open(jobs_path, "w", newline="\n") as handle:
        handle.write("# I-008 record attempt on %s: %d runs of %d s, chunks of %d,\n"
                     "# seeds %d..%d\n"
                     % (INSTANCE, RUNS_TOTAL, SECONDS, RUNS_PER_JOB,
                        FIRST_SEED, FIRST_SEED + RUNS_TOTAL - 1))
        handle.write("\n".join(jobs) + "\n")
    print("attempt: %d jobs -> %s  (%.1f CPU-hours, %d runs of %d s on %s)"
          % (len(jobs), os.path.relpath(jobs_path),
             SECONDS * RUNS_TOTAL / 3600.0, RUNS_TOTAL, SECONDS, INSTANCE))


if __name__ == "__main__":
    main()
