#!/usr/bin/env python3
"""I-032: a focused record hunt on ta23 with the current configuration.

Usage: make_jobs.py hunt

ta29 and ta30 look optimal at their best known: thirteen distinct schedules
there, all exactly optimal against reordering any machine, any relevant pair of
machines and any 30- or 60-operation window (I-032, I-027 to I-029). The next
candidate is ta23: best known 1557, lower bound 1518, so 39 units of room;
this line's best is 1564 (I-006), seven away; and it has never been hunted
with the current configuration, which lowered its mean by 7.8 units at 300 s
(I-030).

One cell, setup/ref_I-021.txt, 800 runs of 40 s, the class budget, in jobs of
5 runs, on fresh seeds 8001 to 8800. A record is proved by its schedule.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXPERIMENT = os.path.abspath(os.path.join(HERE, "..", ".."))
BASE = os.path.join(EXPERIMENT, "setup", "ref_I-021.txt")

INSTANCES = ["ta23"]
RUNS_TOTAL = 800
RUNS_PER_JOB = 5
FIRST_SEED = 8001
BUDGET = 40


def setup_text(instance, runs, seed, tag):
    out = []
    for line in open(BASE).read().splitlines():
        if line.startswith("timelimit = "):
            line = "timelimit = %d" % BUDGET
        elif line.startswith("runs = "):
            line = "runs = %d" % runs
        elif line.startswith("seed = "):
            line = "seed = %d" % seed
        out.append(line)
    header = ("# GENERATED by iter/I-032/make_jobs.py, %s, %s (%d s per run, %d "
              "runs, seed %d). Do not edit.\n" % (instance, tag, BUDGET, runs, seed))
    return header + "\n".join(out) + "\n"


def main():
    if (sys.argv[1:2] or [""])[0] != "hunt":
        raise SystemExit(__doc__)
    setup_dir = os.path.join(HERE, "setups")
    os.makedirs(setup_dir, exist_ok=True)
    jobs = []
    for chunk in range(1, RUNS_TOTAL // RUNS_PER_JOB + 1):
        seed = FIRST_SEED + RUNS_PER_JOB * (chunk - 1)
        tag = "c%03d" % chunk
        for instance in INSTANCES:
            path = os.path.join(setup_dir, "%s_%s.txt" % (instance, tag))
            with open(path, "w", newline="\n") as handle:
                handle.write(setup_text(instance, RUNS_PER_JOB, seed, tag))
            # one results directory per chunk; the two instances in it write
            # files named by instance, so they cannot collide
            jobs.append("%s\tI-032_%s\t%s" % (path, tag, instance))
    with open(os.path.join(HERE, "jobs_hunt.tsv"), "w", newline="\n") as handle:
        handle.write("# I-032 hunt: %s, %d runs each of %d s, seeds %d..%d\n"
                     % (" ".join(INSTANCES), RUNS_TOTAL, BUDGET, FIRST_SEED,
                        FIRST_SEED + RUNS_TOTAL - 1))
        handle.write("\n".join(jobs) + "\n")
    print("hunt: %d jobs, %d runs, %.1f CPU-hours"
          % (len(jobs), len(jobs) * RUNS_PER_JOB,
             len(jobs) * RUNS_PER_JOB * BUDGET / 3600.0))


if __name__ == "__main__":
    main()
