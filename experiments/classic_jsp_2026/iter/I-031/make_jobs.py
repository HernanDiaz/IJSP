#!/usr/bin/env python3
"""I-031: choose the crossover partner by distance instead of at random.

Usage: make_jobs.py filter
       make_jobs.py wave <N>        with N in 1..6; cells from wave_cells.txt

Three cells. `control` is the current configuration, setup/ref_I-021.txt,
where each food source is crossed with an elite candidate chosen at random
(the global best or one of the elite.size best). `far` sets abc.partner = far,
the candidate at the largest Hamming distance from the source; `near` sets
abc.partner = near, the one at the smallest non-zero distance. The candidate
set is the existing elite; no parameter.

Where it comes from. The probes after I-029 found the tabu search's optima
exactly optimal against reordering any machine even 2-3 % from the best known
on the large instances: what is left lies in which basins get explored, and
that is recombination's job. Distant parents should seed children in new
basins for I-021's deep chain to exploit; near parents are the opposite bet,
intensification. The pre-launch check moved the mean parent distance from
0.83-0.92 (random) to 0.96-0.97 (far) and 0.67-0.73 (near).

Filter on seeds 1001 to 1030, outside the waves' 1 to 30. One run per job,
one results directory per job.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXPERIMENT = os.path.abspath(os.path.join(HERE, "..", ".."))
BASE = os.path.join(EXPERIMENT, "setup", "ref_I-021.txt")

FILTER_RUNS = 30
FILTER_FIRST_SEED = 1001
WAVE_RUNS = 5
WAVES = 6
BUDGET = {"20x20": 40, "30x15": 100, "30x20": 150}
SIZE = {}
for row in open(os.path.join(EXPERIMENT, "taillard_bounds.csv")):
    f = row.strip().split(",")
    if f[0] != "instance":
        SIZE[f[0]] = f[1] + "x" + f[2]
FULL = ["ta22", "ta23", "ta25", "ta26", "ta27", "ta29", "ta30", "ta32", "ta33",
        "ta34", "ta40", "ta41", "ta42", "ta43", "ta44", "ta45", "ta46", "ta47",
        "ta48", "ta49", "ta50"]
FILTER = ["ta29", "ta30", "ta23", "ta45"]
CELLS = ["control", "far", "near"]


def wave_cells():
    path = os.path.join(HERE, "wave_cells.txt")
    if not os.path.isfile(path):
        raise SystemExit("wave_cells.txt is written when the filter is decided")
    cells = [c.strip() for c in open(path) if c.strip() and not c.startswith("#")]
    assert cells[0] == "control" and set(cells) <= set(CELLS), cells
    return cells


def setup_text(instance, cell, seed, tag):
    out = []
    for line in open(BASE).read().splitlines():
        if line.startswith("timelimit = "):
            line = "timelimit = %d" % BUDGET[SIZE[instance]]
        elif line.startswith("runs = "):
            line = "runs = 1"
        elif line.startswith("seed = "):
            line = "seed = %d" % seed
        out.append(line)
    if cell != "control":
        out += ["", "# I-031: the crossover partner chosen by distance",
                "abc.partner = %s" % cell]
    header = ("# GENERATED by iter/I-031/make_jobs.py, cell %s, %s, %s (%s, %d s, "
              "1 run, seed %d). Do not edit.\n"
              % (cell, instance, tag, SIZE[instance], BUDGET[SIZE[instance]], seed))
    return header + "\n".join(out) + "\n"


def write(instances, cells, runs, first_seed, tag):
    setup_dir = os.path.join(HERE, "setups")
    os.makedirs(setup_dir, exist_ok=True)
    jobs = []
    for instance in instances:
        for cell in cells:
            for piece in range(1, runs + 1):
                seed = first_seed + piece - 1
                path = os.path.join(setup_dir, "%s_%s_%s_p%02d.txt" % (instance, cell, tag, piece))
                with open(path, "w", newline="\n") as handle:
                    handle.write(setup_text(instance, cell, seed, tag))
                jobs.append("%s\tI-031_%s_p%02d_%s\t%s" % (path, tag, piece, cell, instance))
    with open(os.path.join(HERE, "jobs_%s.tsv" % tag), "w", newline="\n") as handle:
        handle.write("# I-031 %s: %d instances x %d cells x %d runs, one run per job\n"
                     % (tag, len(instances), len(cells), runs))
        handle.write("\n".join(jobs) + "\n")
    cpu = sum(BUDGET[SIZE[i]] * runs * len(cells) for i in instances)
    print("%s: %d jobs, %.1f CPU-hours" % (tag, len(jobs), cpu / 3600.0))


def main():
    which = sys.argv[1] if len(sys.argv) > 1 else ""
    if which == "filter":
        write(FILTER, CELLS, FILTER_RUNS, FILTER_FIRST_SEED, "filter")
    elif which == "wave":
        n = int(sys.argv[2])
        assert 1 <= n <= WAVES
        write(FULL, wave_cells(), WAVE_RUNS, 1 + WAVE_RUNS * (n - 1), "w%d" % n)
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    main()
