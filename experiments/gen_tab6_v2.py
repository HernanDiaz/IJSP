#!/usr/bin/env python3
# Regenerate Phase B group table (Table 6) with classical instances collapsed
# into a single "Classical" row, and produce a supplementary per-instance table
# with all 82 instances.
import csv, statistics, re
from collections import defaultdict

RUNS_CSV = "/mnt/c/Users/diazhernan/CLionProjects/IJSP/Papers/COR_Tabu/data/phaseB_ts/runs_data.csv"
PIS_CSV  = "/mnt/c/Users/diazhernan/CLionProjects/IJSP/experiments/statistical_results_exp4/per_instance_stats.csv"
MAIN_OUT = "/mnt/c/Users/diazhernan/CLionProjects/IJSP/Papers/COR_Tabu/figures/tab_phaseb_groups.tex"
SUPP_OUT = "/mnt/c/Users/diazhernan/CLionProjects/IJSP/Papers/COR_Tabu/figures/tab_phaseb_per_instance.tex"

CLASSICAL_LB = {"abz7":656,"abz8":645,"abz9":661,"ft10":930,"ft20":1165,
                "la21":1046,"la24":935,"la25":977,"la27":1235,"la29":1152,"la38":1196,"la40":1222}
TAI_LB = {
 "tai15_15":[1231,1244,1218,1175,1224,1238,1227,1217,1274,1241],
 "tai20_15":[1357,1367,1342,1345,1339,1360,1462,1377,1332,1348],
 "tai20_20":[1642,1561,1518,1644,1558,1591,1652,1603,1583,1528],
 "tai30_15":[1764,1774,1788,1828,2007,1819,1771,1673,1795,1651],
 "tai30_20":[1906,1884,1809,1948,1997,1957,1807,1912,1931,1833],
 "tai50_15":[2760,2756,2717,2839,2679,2781,2943,2885,2655,2723],
 "tai50_20":[2868,2869,2755,2702,2725,2845,2825,2784,3071,2995],
}

def lb_inst(inst):
    m = re.match(r"^F0\.15\.0\.([a-z]+[0-9]+)_", inst)
    if m: return CLASSICAL_LB[m.group(1)], "classical"
    m = re.match(r"^(tai[0-9]+_[0-9]+)_(\d+)", inst)
    if m: return TAI_LB[m.group(1)][int(m.group(2))-1], m.group(1)
    return None, None

NEIGHS_FOLDER = ["n2","n8","next","n1","n3"]
NEIGH_LATEX   = {"n2":"$N_2$","n8":"$N_8$","next":"$N_{\\rm ext}$","n1":"$N_1$","n3":"$N_3$"}

# Per-instance mean RE from runs_data.csv
re_inst = defaultdict(dict)
with open(RUNS_CSV) as fh:
    rd = csv.DictReader(fh)
    for row in rd:
        n = row["neigh"]; ins = row["instance"]
        lb, _ = lb_inst(ins)
        if lb is None: continue
        re_inst[n].setdefault(ins, []).append((float(row["midpoint"]) - lb) / lb * 100)
mean_re = {n: {ins: statistics.mean(vs) for ins, vs in d.items()} for n, d in re_inst.items()}

# Per-instance med_rt from per_instance_stats.csv
medrt = defaultdict(dict)
with open(PIS_CSV) as fh:
    rd = csv.DictReader(fh)
    for row in rd:
        if row["neigh"] in NEIGHS_FOLDER:
            medrt[row["neigh"]][row["instance"]] = float(row["med_rt"])

# Instance lists per group
groups = defaultdict(list)
for ins in next(iter(mean_re.values())):
    _, g = lb_inst(ins)
    if g == "classical":
        groups["Classical"].append(ins)
    else:
        groups[g].append(ins)

GROUP_ORDER = ["Classical","tai15_15","tai20_15","tai20_20","tai30_15","tai30_20","tai50_15","tai50_20"]
GROUP_LABEL = {"Classical":"Classical","tai15_15":"$15{\\times}15$","tai20_15":"$20{\\times}15$",
               "tai20_20":"$20{\\times}20$","tai30_15":"$30{\\times}15$","tai30_20":"$30{\\times}20$",
               "tai50_15":"$50{\\times}15$","tai50_20":"$50{\\times}20$"}
GROUP_NINST = {g: len(groups[g]) for g in GROUP_ORDER}

# Per-group means
def group_stats(group_name):
    insts = groups[group_name]
    out = {}
    for n in NEIGHS_FOLDER:
        res = [mean_re[n][i] for i in insts]
        rts = [medrt[n][i] for i in insts]
        out[n] = (statistics.mean(res), statistics.median(rts))
    return out

# Grand mean across all 82 instances
def grand_stats():
    all_inst = [i for g in GROUP_ORDER for i in groups[g]]
    out = {}
    for n in NEIGHS_FOLDER:
        res = [mean_re[n][i] for i in all_inst]
        rts = [medrt[n][i] for i in all_inst]
        out[n] = (statistics.mean(res), statistics.median(rts))
    return out

# ────────────────────────────── MAIN TABLE ───────────────────────────────────
main_lines = [
"% ============================================================",
"% Table: Phase B mean RE(%) and median runtime by group x neighbourhood",
"% Generated by gen_tab6_v2.py (classical instances collapsed into one row)",
"% ============================================================",
"\\begin{table*}[t]",
"\\centering\\small\\setlength{\\tabcolsep}{4pt}",
"\\caption{Phase~B: mean RE\\,(\\%) and median runtime $t$\\,(s) per instance group and",
"neighbourhood (irace-tuned TS, 30 runs per instance). Bold: minimum RE\\,(\\%) in each row.",
"The Classical row aggregates the 12 OR-Library instances; Taillard rows aggregate the",
"10 instances of each size class. Per-instance results are provided as supplementary",
"material~\\cite{DiazSupp2026}.}",
"\\label{tab:phaseb_groups}",
"\\begin{tabular}{l r | rr | rr | rr | rr | rr}",
"\\hline",
" &  & \\multicolumn{2}{c|}{$N_2$} & \\multicolumn{2}{c|}{$N_8$} &",
"  \\multicolumn{2}{c|}{$N_{\\rm ext}$} & \\multicolumn{2}{c|}{$N_1$} &",
"  \\multicolumn{2}{c}{$N_3$} \\\\",
"Group & $n$ & RE & $t$ & RE & $t$ & RE & $t$ & RE & $t$ & RE & $t$ \\\\",
"\\hline",
]
for g in GROUP_ORDER:
    s = group_stats(g)
    res_vals = [s[n][0] for n in NEIGHS_FOLDER]
    min_re = min(res_vals)
    cells = []
    for n, (r, t) in [(n, s[n]) for n in NEIGHS_FOLDER]:
        rs = f"{r:.2f}"
        if abs(r - min_re) < 1e-9:
            rs = "\\textbf{" + rs + "}"
        cells += [rs, str(int(round(t)))]
    main_lines.append(f"{GROUP_LABEL[g]:<22s} & {GROUP_NINST[g]:>2d} & " + " & ".join(cells) + " \\\\")
# Grand mean
gs = grand_stats()
gcells = []
for n in NEIGHS_FOLDER:
    r, t = gs[n]
    gcells += [f"{r:.2f}", str(int(round(t)))]
main_lines += [
"\\hline",
f"\\textit{{Grand mean}}   & 82 & " + " & ".join(gcells) + " \\\\",
"\\hline",
"\\end{tabular}",
"\\end{table*}",
]

with open(MAIN_OUT, "w") as fh:
    fh.write("\n".join(main_lines) + "\n")
print(f"[OK] Main table written to {MAIN_OUT}")

# ─────────────────────────── SUPPLEMENTARY TABLE ─────────────────────────────
# Ordered: 12 classical first, then 70 Taillard sorted by group
supp_order = []
for g in GROUP_ORDER:
    if g == "Classical":
        # Order classical by name (abz7..abz9, ft10, ft20, la21..la40)
        order = ["abz7","abz8","abz9","ft10","ft20","la21","la24","la25","la27","la29","la38","la40"]
        order_map = {nm: i for i, nm in enumerate(order)}
        supp_order += sorted(groups[g], key=lambda i: order_map[lb_inst(i)[1] if lb_inst(i)[1]=="classical" else 99] if False else order_map[re.match(r"^F0\.15\.0\.([a-z]+[0-9]+)_", i).group(1)])
    else:
        # tai_xx_yy_NN sorted by NN
        supp_order += sorted(groups[g], key=lambda i: int(re.match(r"^tai[0-9]+_[0-9]+_(\d+)", i).group(1)))

def instance_label(ins):
    m = re.match(r"^F0\.15\.0\.([a-z]+[0-9]+)_", ins)
    if m: return m.group(1).upper().replace("ABZ","ABZ").replace("FT","FT").replace("LA","LA")  # uppercase
    m = re.match(r"^(tai[0-9]+_[0-9]+)_(\d+)", ins)
    if m: return f"{m.group(1)}/{int(m.group(2)):02d}"
    return ins

supp_lines = [
"% ============================================================",
"% Supplementary Table: Phase B per-instance mean RE(%) and median runtime",
"% Generated by gen_tab6_v2.py (one row per instance, all 82 instances)",
"% ============================================================",
"\\begin{longtable}{l | rr | rr | rr | rr | rr}",
"\\caption{Phase~B per-instance results (supplementary): mean RE\\,(\\%) and median",
"runtime $t$\\,(s) per instance and neighbourhood (irace-tuned TS, 30 runs per instance).",
"Bold: minimum RE\\,(\\%) in each row.}",
"\\label{tab:phaseb_per_instance} \\\\",
"\\hline",
" & \\multicolumn{2}{c|}{$N_2$} & \\multicolumn{2}{c|}{$N_8$} &",
"  \\multicolumn{2}{c|}{$N_{\\rm ext}$} & \\multicolumn{2}{c|}{$N_1$} &",
"  \\multicolumn{2}{c}{$N_3$} \\\\",
"Instance & RE & $t$ & RE & $t$ & RE & $t$ & RE & $t$ & RE & $t$ \\\\",
"\\hline",
"\\endfirsthead",
"\\multicolumn{11}{l}{\\small\\itshape (continued from previous page)} \\\\",
"\\hline",
" & \\multicolumn{2}{c|}{$N_2$} & \\multicolumn{2}{c|}{$N_8$} &",
"  \\multicolumn{2}{c|}{$N_{\\rm ext}$} & \\multicolumn{2}{c|}{$N_1$} &",
"  \\multicolumn{2}{c}{$N_3$} \\\\",
"Instance & RE & $t$ & RE & $t$ & RE & $t$ & RE & $t$ & RE & $t$ \\\\",
"\\hline",
"\\endhead",
"\\hline",
"\\endfoot",
]
prev_group = None
for ins in supp_order:
    _, g = lb_inst(ins)
    grp = "Classical" if g == "classical" else g
    if prev_group is not None and prev_group != grp:
        supp_lines.append("\\hline")
    prev_group = grp
    res_vals = [mean_re[n][ins] for n in NEIGHS_FOLDER]
    min_re = min(res_vals)
    cells = []
    for n in NEIGHS_FOLDER:
        r = mean_re[n][ins]; t = medrt[n][ins]
        rs = f"{r:.2f}"
        if abs(r - min_re) < 1e-9:
            rs = "\\textbf{" + rs + "}"
        cells += [rs, str(int(round(t)))]
    supp_lines.append(f"{instance_label(ins):<14s} & " + " & ".join(cells) + " \\\\")

supp_lines += ["\\end{longtable}"]

with open(SUPP_OUT, "w") as fh:
    fh.write("\n".join(supp_lines) + "\n")
print(f"[OK] Supplementary table written to {SUPP_OUT}")

# ─────────────────────────── Stats for paragraph ─────────────────────────────
# Winners per group (8 rows, since classical is now one)
print("\n=== Winners per GROUP (new 8-row structure) ===")
wins_grp = defaultdict(int)
for g in GROUP_ORDER:
    s = group_stats(g)
    res_vals = {n: round(s[n][0], 4) for n in NEIGHS_FOLDER}
    mn = min(res_vals.values())
    wins = [n for n,v in res_vals.items() if v == mn]
    for w in wins: wins_grp[w] += 1
    print(f"  {GROUP_LABEL[g]:<20s} winner={','.join(wins)}  (RE={mn:.4f})")
print("\n  Win totals:")
for n in NEIGHS_FOLDER:
    print(f"    {n}: {wins_grp[n]} of 8")
